class Key:
    def __init__(self, code, key_spec):
        self.code = code
        self.key_spec = key_spec
        self.character_map_keys = None
        self.multitap_keys = []
        self.more_keys = []
        self.engine_keys = []


class Document:
    def __init__(self, doc_id, name, languages, targets, sources, layout_set=ANY):
        self.id = doc_id
        self.name = name
        self.languages = languages
        self.targets = targets
        self.sources = sources
        # The layout set the document's tables belong to, or "any" when it serves several.
        self.layout_set = layout_set
        self.rows_template = None
        self.keys = []
        self.notes = []
        # (table file, label, lists) for table entries no key of this document types.
        self.unplaced = []

    def signature(self):
        return [(k.code, k.key_spec, k.character_map_keys, tuple(k.multitap_keys), tuple(k.more_keys),
                 tuple(k.engine_keys)) for k in self.keys]


# Key-spec flags and references (!fixedColumnOrder!3, !hasLabels!, !icon/..., !code/...). A lone
# "!" is the exclamation mark itself and stays.
FLAG_TOKEN = re.compile(r"^!(?:[A-Za-z]+!|icon/|code/|text/)")


def entry_problem(value):
    """Why the parser (LetterLayoutXml.checkEntry) would refuse a list entry, or None: 1 to
    MAX_ENTRY code points, no control character or lone surrogate, and an entry of more than one
    code point does not begin or end with white space."""
    if not 1 <= len(value) <= MAX_ENTRY:
        return "%d code points, the format allows 1 to %d" % (len(value), MAX_ENTRY)
    if any(unicodedata.category(c) in ("Cc", "Cs") for c in value):
        return "holds a control character"
    if len(value) > 1 and (value[0].isspace() or value[-1].isspace()):
        return "begins or ends with white space"
    return None


def clean_list(doc_id, code, field, tokens):
    """A resolved key-spec list as §11.1 allows it: no ! tokens, escapes undone, 1 to 8 code
    points per entry, at most 32 entries. Everything dropped is reported against the key and
    field."""
    out = []
    for token in tokens or []:
        if FLAG_TOKEN.match(token):
            warn("%s %s %s: dropped the flag token %r" % (doc_id, code, field, token))
            continue
        value = unescape_token(token)
        problem = entry_problem(value)
        if problem:
            warn("%s %s %s: dropped %r (%s): %s"
                 % (doc_id, code, field, value, " ".join(fmt_cp(ord(c)) for c in value), problem))
            continue
        if value in out:
            # Kept: the old list shows it twice too, and §11 does not forbid it.
            warn("%s %s %s: %r appears twice in the source list; kept as it is"
                 % (doc_id, code, field, value))
        out.append(value)
    if len(out) > MAX_LIST:
        warn("%s %s %s: %d entries, cut to the first %d (format cap): dropped %s"
             % (doc_id, code, field, len(out), MAX_LIST, ",".join(out[MAX_LIST:])))
        out = out[:MAX_LIST]
    return out


def place_table(doc, table, typed_labels):
    """Moves the table's hold lists onto the keys whose letter is the entry's label, and reports
    the labels no key types (currency keys, punctuation the layout puts elsewhere)."""
    by_letter = {k.key_spec: k for k in doc.keys}
    for label in table.order:
        key = by_letter.get(label)
        if key is None:
            if label in typed_labels:
                continue
            lists = []
            for field, values in (("moreKeys", table.more_keys.get(label)),
                                  ("multitapKeys", table.multitap.get(label)),
                                  ("characterMapKeys", table.char_map.get(label))):
                if values:
                    lists.append("%s=%s" % (field, ",".join(values)))
            doc.unplaced.append((table.file_name, label, " ".join(lists) or "no lists"))
            continue
        key.more_keys = clean_list(doc.id, key.code, "moreKeys", table.more_keys.get(label))


def script_document(doc_id, language, layout_set, table, layout, sources):
    name = LANGUAGE_NAMES[language]
    if doc_id != language:
        name += " (%s)" % layout_set
    # Bound to the layout set whose table it carries: the plain and the translit keyboard of a
    # language share its letters but not its lists, and the registry tells them apart by this.
    doc = Document(doc_id, name, [language], "pkb", sources, layout_set=layout_set)
    if layout.nordic_form_keys:
        warn("%s: %d keys in %s carry keyLabel and keyCodes; the first code is the letter, as "
             "the old HardwareScriptLayout.parse read it" % (doc_id, layout.nordic_form_keys, rel(layout.path)))
    cells = []
    for row in KEYCODE_ROWS:
        for letter in row:
            code = "KEYCODE_" + letter
            codes = layout.cells.get(code)
            if codes is None:
                warn("%s: %s has no letter in %s; the key falls through to the key map"
                     % (doc_id, code, rel(layout.path)))
                continue
            cells.append((code, codes))
    if layout.extra is not None:
        if java_is_letter(layout.extra[0]):
            cells.append(("KEYCODE_4", layout.extra))
        else:
            doc.notes.append("The key past M (KEYCODE_4) carries %s in the engine layout, not a "
                             "letter, so it stays the currency key." % chr(layout.extra[0]))
            warn("%s: the key past M carries %s in %s, not a letter; no KEYCODE_4 key"
                 % (doc_id, chr(layout.extra[0]), rel(layout.path)))
    for code, codes in cells:
        letter = codes[0]
        key = Key(code, chr(letter))
        # The old HardwareScriptLayouts.letterOf with Shift: the upper case where the script has one,
        # else the table's Shift legend, else the key's second legend, else the letter itself.
        upper = java_upper(letter)
        if upper != letter:
            shifted = upper
        else:
            legend = table.shift_legend(chr(letter))
            if legend:
                shifted = ord(legend[0])
                if len(legend) != 1:
                    warn("%s %s characterMapKeys: the table's Shift legend %r is %d code points; "
                         "the first is what Shift types" % (doc_id, code, legend, len(legend)))
            elif len(codes) > 1:
                shifted = codes[1]
            else:
                shifted = letter
        if shifted != java_upper(letter):
            key.character_map_keys = chr(shifted)
        # The old HardwareScriptLayouts.alternatesFor: on a cased script the further legends are
        # the double-tap sequence; a caseless script has none, and while a script layout drove the
        # keys the table's multitap lists were never read (KeyboardSwitcher.getMoreKeysForKeyByStyle).
        if len(codes) > 1 and java_upper(letter) != letter:
            key.multitap_keys = clean_list(doc_id, code, "multitapKeys",
                                           [chr(c) for c in codes[1:]])
        doc.keys.append(key)
    typed = {k.key_spec for k in doc.keys}
    place_table(doc, table, typed)
    for label, values in sorted(table.multitap.items()):
        warn("%s: %s multitapKeys for %r (%s) are never read while the script layout drives the "
             "keys; the double-tap list comes from the engine layout" % (doc_id, table.file_name,
                                                                         label, ",".join(values)))
    return doc


def latin_document(language, table, sources, layout_set=None):
    """A Latin-letter document for [language]: bound to any layout set, or, when [layout_set] is
    given, named <language>-<layout set> and bound to that one."""
    if layout_set is None:
        doc = Document(language, LANGUAGE_NAMES[language], [language], "pkb", sources)
    else:
        doc = Document("%s-%s" % (language, layout_set), "%s (%s)" % (LANGUAGE_NAMES[language], layout_set),
                       [language], "pkb", sources, layout_set=layout_set)
    for row in KEYCODE_ROWS:
        for letter in row:
            doc.keys.append(Key("KEYCODE_" + letter, letter.lower()))
    typed = {k.key_spec for k in doc.keys}
    place_table(doc, table, typed)
    for label, values in sorted(table.multitap.items()):
        if label in typed:
            key = next(k for k in doc.keys if k.key_spec == label)
            key.multitap_keys = clean_list(doc.id, key.code, "multitapKeys", values)
    for label, values in sorted(table.char_map.items()):
        if label in typed and values:
            key = next(k for k in doc.keys if k.key_spec == label)
            if values[0] != chr(java_upper(ord(label))):
                key.character_map_keys = values[0]
    return doc


