#!/usr/bin/env python3
"""Generate the built-in letter-layout documents, app/src/main/assets/letter-layouts/<id>.xml.

Run from the repository root:

    python3 xt9kdb-scaffold/tools/letter_layouts_gen.py

Standard library only. The output is deterministic: running it twice over the same sources writes
the same bytes, and a source change shows up as a reviewable diff of the generated files.

What a physical key does today comes from three places, and this script folds them into one
document per language (format: §11 and its v1.1 amendments §11.1 of
bbkb-attic/docs/2026-10_unified-pkb-layouts_plan.md):

  * the letter a key types: the engine's hardware layout, assets/kdb/<name>_pkb.xml, for the seven
    languages with an alphabet of their own on the keys (SCRIPT_KDB), read with exactly the
    position rules the old HardwareScriptLayout.parse used; every other language types the Latin
    letter the firmware key map gives, a-z on KEYCODE_A..KEYCODE_Z;
  * the Shift legend, double-tap and hold lists: the label-keyed tables BlackBerry shipped as
    res/xml/pkbd_*.xml, kept beside this script in letter_layouts_tables/ since the app stopped
    reading them (the documents replaced them), chosen by layout set as the <switch> in
    kbd_alphabet_pkb.xml chose them (PKBD_CASES), with their !text/ references resolved through the
    per-locale tables in KeyboardTextSet.java;
  * which language uses which tables: res/xml/method.xml, plus the built-in translit keyboards
    (res/values/arrays.xml, predefined_builtin_keyboard_subtypes).

Colemak and Dvorak, which no subtype names, come from res/xml/rowkeys_colemak1..3.xml and
rowkeys_dvorak1..3.xml.

A document derived from one layout set's tables is bound to that layout set (<bind layoutSet>):
the three translit documents to `translit`, the script documents to the set their keyboard uses
(arabic, east_slavic, hangul, hebrew, greek), so Russian and Russian (translit) can be told apart.
Latin documents serve several layout sets (qwerty, qwertz, azerty, ...) and stay `any`, except for
a language that also has a keyboard with no physical-key table: `any` would reach that keyboard
too, so the language gets one document per layout set that has tables, named
<language>-<layout set> and bound to it. Chinese is the case today: zh-pinyin and zh-cangjie, and
nothing for the stroke and Zhuyin keyboards, which keep the firmware key map.

List entries are strings of 1 to 8 code points (the tables offer ligatures: Arabic lam-alef,
Hebrew letters with geresh, Catalan l·l, Uzbek oʻ and gʻ), at most 32 to a list.

The script prints a report: the documents written and every warning (list entries dropped because
the format cannot hold them, references it could not resolve, table entries that no key types,
lists cut to the format's 32-entry cap) and the multi-character entries the documents carry.
"""

