def entry_problem(value):
    """Why the parser (LetterLayoutXml.checkEntry) would refuse a list entry, or None: 1 to
    MAX_ENTRY code points, no control character or lone surrogate, and an entry of more than one
    code point does not begin or end with white space."""
    if not 1 <= len(value) <= MAX_ENTRY:
        return "%d code points, the format allows 1 to %d" % (len(value), MAX_ENTRY)
    if any(unicodedata.category(c) in ("Cc", "Cs") for c in value):
        return "holds a control character"
    if len(value) > 1 and (value[0].isspace() or value[-1].isspace()):
        return "begins or ends with white space"
    return None


def clean_list(doc_id, code, field, tokens):
    """A resolved key-spec list as §11.1 allows it: no ! tokens, escapes undone, 1 to 8 code
    points per entry, at most 32 entries. Everything dropped is reported against the key and
    field."""
    out = []
    for token in tokens or []:
        if FLAG_TOKEN.match(token):
            warn("%s %s %s: dropped the flag token %r" % (doc_id, code, field, token))
            continue
        value = unescape_token(token)
        problem = entry_problem(value)
        if problem:
            warn("%s %s %s: dropped %r (%s): %s"
                 % (doc_id, code, field, value, " ".join(fmt_cp(ord(c)) for c in value), problem))
            continue
        if value in out:
            # Kept: the old list shows it twice too, and §11 does not forbid it.
            warn("%s %s %s: %r appears twice in the source list; kept as it is"
                 % (doc_id, code, field, value))
        out.append(value)
    if len(out) > MAX_LIST:
        warn("%s %s %s: %d entries, cut to the first %d (format cap): dropped %s"
             % (doc_id, code, field, len(out), MAX_LIST, ",".join(out[MAX_LIST:])))
        out = out[:MAX_LIST]
    return out


def place_table(doc, table, typed_labels):
    """Moves the table's hold lists onto the keys whose letter is the entry's label, and reports
    the labels no key types (currency keys, punctuation the layout puts elsewhere)."""
    by_letter = {k.key_spec: k for k in doc.keys}
    for label in table.order:
        key = by_letter.get(label)
        if key is None:
            if label in typed_labels:
                continue
            lists = []
            for field, values in (("moreKeys", table.more_keys.get(label)),
                                  ("multitapKeys", table.multitap.get(label)),
                                  ("characterMapKeys", table.char_map.get(label))):
                if values:
                    lists.append("%s=%s" % (field, ",".join(values)))
            doc.unplaced.append((table.file_name, label, " ".join(lists) or "no lists"))
            continue
        key.more_keys = clean_list(doc.id, key.code, "moreKeys", table.more_keys.get(label))


def script_document(doc_id, language, layout_set, table, layout, sources):
    name = LANGUAGE_NAMES[language]
    if doc_id != language:
        name += " (%s)" % layout_set
    # Bound to the layout set whose table it carries: the plain and the translit keyboard of a
    # language share its letters but not its lists, and the registry tells them apart by this.
    doc = Document(doc_id, name, [language], "pkb", sources, layout_set=layout_set)
    if layout.nordic_form_keys:
        warn("%s: %d keys in %s carry keyLabel and keyCodes; the first code is the letter, as "
             "the old HardwareScriptLayout.parse read it" % (doc_id, layout.nordic_form_keys, rel(layout.path)))
    cells = []
    for row in KEYCODE_ROWS:
        for letter in row:
            code = "KEYCODE_" + letter
            codes = layout.cells.get(code)
            if codes is None:
                warn("%s: %s has no letter in %s; the key falls through to the key map"
                     % (doc_id, code, rel(layout.path)))
                continue
            cells.append((code, codes))
    if layout.extra is not None:
        if java_is_letter(layout.extra[0]):
            cells.append(("KEYCODE_4", layout.extra))
        else:
            doc.notes.append("The key past M (KEYCODE_4) carries %s in the engine layout, not a "
                             "letter, so it stays the currency key." % chr(layout.extra[0]))
            warn("%s: the key past M carries %s in %s, not a letter; no KEYCODE_4 key"
                 % (doc_id, chr(layout.extra[0]), rel(layout.path)))
    for code, codes in cells:
        letter = codes[0]
        key = Key(code, chr(letter))
        # The old HardwareScriptLayouts.letterOf with Shift: the upper case where the script has one,
        # else the table's Shift legend, else the key's second legend, else the letter itself.
        upper = java_upper(letter)
        if upper != letter:
            shifted = upper
        else:
            legend = table.shift_legend(chr(letter))
            if legend:
                shifted = ord(legend[0])
                if len(legend) != 1:
                    warn("%s %s characterMapKeys: the table's Shift legend %r is %d code points; "
                         "the first is what Shift types" % (doc_id, code, legend, len(legend)))
            elif len(codes) > 1:
                shifted = codes[1]
            else:
                shifted = letter
        if shifted != java_upper(letter):
            key.character_map_keys = chr(shifted)
        # The old HardwareScriptLayouts.alternatesFor: on a cased script the further legends are
        # the double-tap sequence; a caseless script has none, and while a script layout drove the
        # keys the table's multitap lists were never read (KeyboardSwitcher.getMoreKeysForKeyByStyle).
        if len(codes) > 1 and java_upper(letter) != letter:
            key.multitap_keys = clean_list(doc_id, code, "multitapKeys",
                                           [chr(c) for c in codes[1:]])
        doc.keys.append(key)
    typed = {k.key_spec for k in doc.keys}
    place_table(doc, table, typed)
    for label, values in sorted(table.multitap.items()):
        warn("%s: %s multitapKeys for %r (%s) are never read while the script layout drives the "
             "keys; the double-tap list comes from the engine layout" % (doc_id, table.file_name,
                                                                         label, ",".join(values)))
    return doc


def latin_document(language, table, sources, layout_set=None):
    """A Latin-letter document for [language]: bound to any layout set, or, when [layout_set] is
    given, named <language>-<layout set> and bound to that one."""
    if layout_set is None:
        doc = Document(language, LANGUAGE_NAMES[language], [language], "pkb", sources)
    else:
        doc = Document("%s-%s" % (language, layout_set), "%s (%s)" % (LANGUAGE_NAMES[language], layout_set),
                       [language], "pkb", sources, layout_set=layout_set)
    for row in KEYCODE_ROWS:
        for letter in row:
            doc.keys.append(Key("KEYCODE_" + letter, letter.lower()))
    typed = {k.key_spec for k in doc.keys}
    place_table(doc, table, typed)
    for label, values in sorted(table.multitap.items()):
        if label in typed:
            key = next(k for k in doc.keys if k.key_spec == label)
            key.multitap_keys = clean_list(doc.id, key.code, "multitapKeys", values)
    for label, values in sorted(table.char_map.items()):
        if label in typed and values:
            key = next(k for k in doc.keys if k.key_spec == label)
            if values[0] != chr(java_upper(ord(label))):
                key.character_map_keys = values[0]
    return doc


def rowkeys_document(doc_id, name, texts, table_key):
    """Colemak or Dvorak from its three rowkeys files: each <Key> in row order on the QWERTY key
    code of its position. Row 1 holds Q..P; row 2 A..L and, for a tenth key, KEYCODE_SEMICOLON
    (the key right of L on a QWERTY board); row 3 Z..M then KEYCODE_COMMA, KEYCODE_PERIOD and
    KEYCODE_SLASH for further keys. A <switch> contributes its <default> (the unshifted alphabet);
    a case naming the shifted alphabet elements gives that key's Shift legend."""
    doc = Document(doc_id, name, [], "pkb,vkb",
                   ["res/xml/rowkeys_%s1..3.xml" % doc_id, "KeyboardTextSet en table"])
    doc.rows_template = "qwerty"
    row_codes = [["KEYCODE_" + c for c in KEYCODE_ROWS[0]],
                 ["KEYCODE_" + c for c in KEYCODE_ROWS[1]] + ["KEYCODE_SEMICOLON"],
                 ["KEYCODE_" + c for c in KEYCODE_ROWS[2]] + ["KEYCODE_COMMA", "KEYCODE_PERIOD",
                                                             "KEYCODE_SLASH"]]
    shifted_elements = {"alphabetManualShifted", "alphabetShiftLocked", "alphabetShiftLockShifted"}

    def keys_of(element, shifted):
        """The <Key>s an element contributes, in order, descending into includes and switches."""
        out = []
        for child in element:
            if child.tag == "Key":
                out.append(child)
            elif child.tag == "include":
                target = child.get(LATIN_NS + "keyboardLayout").replace("@xml/", "")
                out.extend(keys_of(ET.parse(os.path.join(RES_XML, target + ".xml")).getroot(), shifted))
            elif child.tag == "switch":
                chosen = None
                for case in child:
                    elements = set((case.get(LATIN_NS + "keyboardLayoutSetElement") or "").split("|"))
                    if case.tag == "default" or (shifted and elements & shifted_elements and
                                                 len(case.attrib) == 1):
                        chosen = case
                        break
                if chosen is not None:
                    out.extend(keys_of(chosen, shifted))
        return out

    for row in range(3):
        path = os.path.join(RES_XML, "rowkeys_%s%d.xml" % (doc_id, row + 1))
        root = ET.parse(path).getroot()
        plain = keys_of(root, False)
        shifted = keys_of(root, True)
        if len(plain) > len(row_codes[row]):
            warn("%s: row %d has %d keys, more than the %d positions named for it; the rest are "
                 "dropped" % (doc_id, row + 1, len(plain), len(row_codes[row])))
        for index, element in enumerate(plain[:len(row_codes[row])]):
            code = row_codes[row][index]
            spec = texts.resolve(element.get(LATIN_NS + "keySpec"), table_key)
            if not spec or len(spec) != 1:
                warn("%s %s: keySpec %r is not one code point; key skipped" % (doc_id, code, spec))
                continue
            key = Key(code, spec)
            more = filter_more_key_flags(split_key_specs(texts.resolve(element.get(LATIN_NS + "moreKeys"),
                                                                       table_key)))
            key.more_keys = clean_list(doc_id, code, "moreKeys", more)
            if index < len(shifted) and shifted[index] is not element:
                legend = texts.resolve(shifted[index].get(LATIN_NS + "keySpec"), table_key)
                if legend and len(legend) == 1 and ord(legend) != java_upper(ord(spec)):
                    key.character_map_keys = legend
            doc.keys.append(key)
        if len(plain) < len(KEYCODE_ROWS[row]):
            missing = [c for c in row_codes[row][len(plain):len(KEYCODE_ROWS[row])]]
            doc.notes.append("Row %d has %d keys, so %s carry nothing here and fall through to "
                             "the key map." % (row + 1, len(plain), ", ".join(missing)))
    present = {k.key_spec for k in doc.keys}
    absent = [c for c in "abcdefghijklmnopqrstuvwxyz" if c not in present]
    if absent:
        warn("%s: no key types %s" % (doc_id, ", ".join(absent)))
    return doc


# ── writing ──────────────────────────────────────────────────────────────────────────────────────

def xml_attr(value):
    out = []
    for c in value:
        if c == "&":
            out.append("&amp;")
        elif c == "<":
            out.append("&lt;")
        elif c == ">":
            out.append("&gt;")
        elif c == '"':
            out.append("&quot;")
        elif c != " " and unicodedata.category(c) in ("Cc", "Zs", "Zl", "Zp", "Cf"):
            # Invisible and white-space characters as references: XML would fold a raw tab or
            # line break in an attribute into a space, and the others cannot be seen in review.
            out.append("&#x%X;" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def list_attr(values):
    return ",".join(v.replace("\\", "\\\\").replace(",", "\\,") for v in values)


def comment_text(text):
    return text.replace("--", "- -")


def render(doc):
    lines = ["<!-- %s -->" % HEADER]
    lines.append("<!-- Sources: %s. -->" % comment_text("; ".join(doc.sources)))
    for note in doc.notes:
        lines.append("<!-- %s -->" % comment_text(note))
    lines.append('<letter-layout version="1" id="%s" name="%s" targets="%s">'
                 % (doc.id, xml_attr(doc.name), doc.targets))
    lines.append('    <bind languages="%s" keypad="any" keypadType="any" layoutSet="%s"/>'
                 % (",".join(doc.languages), doc.layout_set))
    if doc.rows_template:
        lines.append('    <rows template="%s"/>' % doc.rows_template)
    for key in doc.keys:
        parts = ['code="%s"' % key.code, 'keySpec="%s"' % xml_attr(key.key_spec)]
        if key.character_map_keys:
            parts.append('characterMapKeys="%s"' % xml_attr(key.character_map_keys))
        if key.multitap_keys:
            parts.append('multitapKeys="%s"' % xml_attr(list_attr(key.multitap_keys)))
        if key.more_keys:
            parts.append('moreKeys="%s"' % xml_attr(list_attr(key.more_keys)))
        lines.append("    <key %s/>" % " ".join(parts))
    lines.append("</letter-layout>")
    return "\n".join(lines) + "\n"


def validate(doc):
    """The §11 / §11.1 rules a generated document must meet; a failure here is a generator bug."""
    assert re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,63}", doc.id), doc.id
    assert 1 <= len(doc.name) <= 64, doc.name
    assert len(doc.keys) <= MAX_KEYS, doc.id
    assert len(doc.languages) <= 32, doc.id
    assert doc.layout_set == ANY or re.fullmatch(r"[a-z0-9_]{1,64}", doc.layout_set), (doc.id, doc.layout_set)
    codes = [k.code for k in doc.keys]
    assert len(codes) == len(set(codes)), "duplicate key in " + doc.id
    for k in doc.keys:
        assert len(k.key_spec) == 1, (doc.id, k.code)
        assert k.character_map_keys is None or len(k.character_map_keys) == 1, (doc.id, k.code)
        for values in (k.multitap_keys, k.more_keys):
            assert len(values) <= MAX_LIST, (doc.id, k.code)
            assert all(entry_problem(v) is None for v in values), (doc.id, k.code, values)


# ── main ─────────────────────────────────────────────────────────────────────────────────────────

def main():
    texts = TextTables(TEXT_SET_JAVA)
    files = SCRIPT_KDB
    pkbd_cases, pkbd_default = PKBD_CASES, PKBD_DEFAULT
    subtypes = read_subtypes()

    # Languages typed on Latin keys that also have a keyboard with no physical-key table (Chinese:
    # stroke and Zhuyin beside pinyin and cangjie). A document bound to any layout set would reach
    # that keyboard too, so these languages get one document per layout set that has tables.
    per_layout_set = set()
    for locale, layout_set, origin in subtypes:
        language = language_code(locale)
        if language not in files and not physical_keyboard_of(layout_set)[1]:
            per_layout_set.add(language)

    documents = {}
    skipped = []
    for locale, layout_set, origin in subtypes:
        language = language_code(locale)
        table_key = texts.table_key_for(locale_string(locale), language)
        table_file = pkbd_cases.get(layout_set, pkbd_default)
        subtype_note = "subtype %s:%s (%s)" % (locale, layout_set, origin)
        mark = len(warnings)
        kbd, has_tables = physical_keyboard_of(layout_set)
        if language in files:
            # The seven languages whose keys type their own alphabet (while the "Use active
            # language's alphabet" switch is on). The translit keyboards share the letters and
            # differ in their tables, so they are documents of their own.
            if not has_tables:
                raise ValueError("%s: layout set %s has no physical-key tables" % (locale, layout_set))
            doc_id = language + "-translit" if layout_set == "translit" else language
            layout = load_script_layout(files[language])
            if not layout.script:
                raise ValueError("%s is not a script layout" % files[language])
            table = PkbdTable(table_file, layout_set, language, table_key, texts)
            sources = ["letters %s" % rel(layout.path),
                       "Shift legends and lists xt9kdb-scaffold/tools/letter_layouts_tables/%s.xml for layout set %s" % (table_file, layout_set),
                       "text table %s" % table_key, subtype_note]
            doc = script_document(doc_id, language, layout_set, table, layout, sources)
        elif has_tables and table_file == pkbd_default:
            # Every other keyboard whose physical keyboard is kbd_alphabet_pkb types the key map's
            # Latin letters, and the Latin table's lists (keyed by those letters) apply to it
            # whatever its on-screen alphabet is (romaji, pinyin, cangjie).
            table = PkbdTable(table_file, layout_set, language, table_key, texts)
            sources = ["letters a-z on KEYCODE_A..KEYCODE_Z (the firmware key map)",
                       "lists xt9kdb-scaffold/tools/letter_layouts_tables/%s.xml for layout set %s" % (table_file, layout_set),
                       "text table %s" % table_key, subtype_note]
            doc = latin_document(language, table, sources,
                                 layout_set if language in per_layout_set else None)
        elif has_tables:
            # A script table (pkbd_slavic) on a keyboard whose keys type Latin letters: every entry
            # is keyed by a letter those keys never type, so nothing of it is reachable.
            skipped.append((locale, layout_set, "table %s is keyed by letters the keys never type"
                            % table_file))
            continue
        else:
            # The layout set has no alphabetPkb element, so the physical keys get the on-screen
            # alphabet, which carries no physical-key table: the key map's letters, nothing more.
            skipped.append((locale, layout_set, "no physical-key table (the physical keyboard is %s)" % kbd))
            continue
        validate(doc)
        existing = documents.get(doc.id)
        if existing is None:
            documents[doc.id] = doc
            continue
        if existing.layout_set != doc.layout_set:
            # One document can name one layout set; a second set for the same id needs an id of
            # its own, as the translit keyboards have.
            raise ValueError("%s: %s is for layout set %s, but %s made the document for %s"
                             % (doc.id, subtype_note, doc.layout_set, existing.sources[-1],
                                existing.layout_set))
        if existing.signature() != doc.signature():
            del warnings[mark:]
            warn("%s: %s would give a different document than %s; the first is kept"
                 % (doc.id, subtype_note, existing.sources[-1]))
        else:
            # The same document again (en_US, en_GB, ...): its warnings were already reported.
            del warnings[mark:]
            existing.sources.append(subtype_note)

    # A Latin document is bound to its language on any layout set: where one keyboard of a
    # language has a document and another has nothing today (Chinese stroke beside pinyin), the
    # document reaches the second one too once the registry selects by binding.
    for locale, layout_set, reason in skipped:
        language = language_code(locale)
        bound = [d.id for d in documents.values()
                 if language in d.languages and d.layout_set in (ANY, layout_set)]
        if bound:
            warn("%s:%s has nothing today (%s), but %s is bound to its language %s on any layout set"
                 % (locale, layout_set, reason, ", ".join(sorted(bound)), language))
    # Two language documents with the same binding could never both be selected; the registry
    # would always take the one named after the language, and the other would be dead weight.
    # (Colemak and Dvorak, bound to no language, are chosen by the user and are not checked.)
    bindings = {}
    for doc_id in sorted(documents):
        doc = documents[doc_id]
        if doc.languages:
            bindings.setdefault((tuple(doc.languages), doc.layout_set), []).append(doc_id)
    for (languages, layout_set), doc_ids in sorted(bindings.items()):
        if len(doc_ids) > 1:
            raise ValueError("%s are all bound to %s on layout set %s; the registry cannot tell them apart"
                             % (", ".join(doc_ids), ",".join(languages), layout_set))

    for doc_id, name in (("colemak", "Colemak"), ("dvorak", "Dvorak")):
        doc = rowkeys_document(doc_id, name, texts, texts.table_key_for("en", "en"))
        validate(doc)
        documents[doc_id] = doc

    os.makedirs(OUT_DIR, exist_ok=True)
    wanted = {doc_id + ".xml" for doc_id in documents}
    for stale in sorted(set(os.listdir(OUT_DIR)) - wanted):
        if stale.endswith(".xml"):
            os.remove(os.path.join(OUT_DIR, stale))
            print("removed stale %s" % stale)
    for doc_id in sorted(documents):
        with open(os.path.join(OUT_DIR, doc_id + ".xml"), "w", encoding="utf-8", newline="\n") as out:
            out.write(render(documents[doc_id]))

    print("Wrote %d documents to %s:" % (len(documents), rel(OUT_DIR)))
    for doc_id in sorted(documents):
        doc = documents[doc_id]
        listed = sum(1 for k in doc.keys if k.more_keys or k.multitap_keys or k.character_map_keys)
        subtypes_of = [src.split(" ")[1] for src in doc.sources if src.startswith("subtype ")]
        print("  %-12s %-28s languages=%-4s layoutSet=%-11s keys=%2d with-lists=%2d  from %s"
              % (doc_id, doc.name, ",".join(doc.languages) or "-", doc.layout_set, len(doc.keys),
                 listed, ", ".join(subtypes_of) or doc.sources[0]))
    print()
    multi = [(doc_id, k.code, field, value)
             for doc_id in sorted(documents) for k in documents[doc_id].keys
             for field, values in (("multitapKeys", k.multitap_keys), ("moreKeys", k.more_keys))
             for value in values if len(value) > 1]
    print("List entries of more than one code point (%d), carried as they are:" % len(multi))
    for doc_id, code, field, value in multi:
        print("  %s %s %s: %r (%s)" % (doc_id, code, field, value, " ".join(fmt_cp(ord(c)) for c in value)))
    longest = max(((len(values), doc_id, k.code, field)
                   for doc_id in sorted(documents) for k in documents[doc_id].keys
                   for field, values in (("multitapKeys", k.multitap_keys), ("moreKeys", k.more_keys))),
                  default=None)
    if longest:
        print("Longest list: %d entries (%s %s %s; the cap is %d)" % (longest + (MAX_LIST,)))
    print()
    print("Keyboards with no document (%d): their keys type the key map's Latin letters and the old "
          "path adds nothing to them:" % len(skipped))
    for locale, layout_set, reason in skipped:
        print("  %-14s layout set %-18s %s" % (locale, layout_set, reason))
    print()
    unplaced = {}
    for doc_id in sorted(documents):
        for entry in documents[doc_id].unplaced:
            unplaced.setdefault(entry, []).append(doc_id)
    print("Table entries no key types (%d). Their lists are not in any document; the currency "
          "symbols belong to the resolver's currency key (plan §7):" % len(unplaced))
    for (table_file, label, lists), doc_ids in sorted(unplaced.items()):
        print("  %s %r (%s U+%04X) %s -> in %s" % (table_file, label, unicodedata.name(label[0], "?"),
                                                  ord(label[0]), lists, ", ".join(doc_ids)))
    print()
    print("Warnings (%d):" % len(warnings))
    for w in warnings:
        print("  " + w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
