def read_subtypes():
    """method.xml's keyboard subtypes in file order, plus the built-in translit keyboards:
    [(locale, layout set)]. A subtype without a KeyboardLayoutSet extra value takes it from
    arrays.xml's locale_and_extra_value_to_keyboard_layout_set_map, as ResourceLocaleUtils does."""
    arrays = ET.parse(os.path.join(MAIN, "res", "values", "arrays.xml")).getroot()

    def array(name):
        for a in arrays:
            if a.get("name") == name:
                return [i.text or "" for i in a.findall("item")]
        raise ValueError("array %s not in arrays.xml" % name)

    pairs = array("locale_and_extra_value_to_keyboard_layout_set_map")
    by_locale_and_extra = dict(zip(pairs[0::2], pairs[1::2]))
    subtypes = []
    method = ET.parse(os.path.join(RES_XML, "method.xml")).getroot()
    for st in method.findall("subtype"):
        if st.get(ANDROID_NS + "imeSubtypeMode") != "keyboard":
            continue
        locale = st.get(ANDROID_NS + "imeSubtypeLocale")
        extra = st.get(ANDROID_NS + "imeSubtypeExtraValue", "")
        m = re.search(r"(?:^|,)KeyboardLayoutSet=([^,]*)", extra)
        layout = m.group(1) if m else by_locale_and_extra.get(locale + ":" + extra)
        if layout is None:
            raise ValueError("method.xml subtype %s has no keyboard layout set" % locale)
        subtypes.append((locale, layout, "method.xml"))
    for item in array("predefined_builtin_keyboard_subtypes"):
        locale, layout = item.split(":")
        subtypes.append((locale, layout, "arrays.xml predefined_builtin_keyboard_subtypes"))
    declared = {language_code(locale) for locale, _, _ in subtypes}
    for language, layout in read_sideloaded_subtypes():
        if layout in SIDELOADED_LAYOUT_SETS and language not in declared:
            subtypes.append((language, layout, "SideloadedSubtypes.java"))
    return subtypes


def read_sideloaded_subtypes():
    """SideloadedSubtypes.LAYOUT_FOR_LANGUAGE, read off the Java: [(language, layout set)]."""
    with open(SIDELOADED_JAVA, encoding="utf-8") as f:
        java = f.read()
    out = []
    latin = re.search(r'for \(String latin : new String\[\] \{([^}]*)\}\)\s*\{\s*m\.put\(latin, "([a-z_]+)"\)', java)
    if latin:
        for language in re.findall(r'"([a-z]+)"', latin.group(1)):
            out.append((language, latin.group(2)))
    for language, layout in re.findall(r'm\.put\("([a-z]+)", "([a-z_]+)"\)', java):
        out.append((language, layout))
    return out


