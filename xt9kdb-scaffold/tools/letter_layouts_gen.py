# ── code points and Java's character rules ───────────────────────────────────────────────────────

def java_upper(cp):
    """Java's Character.toUpperCase(int): the simple mapping, the code point itself when the full
    mapping is longer than one character (ΐ, ß) or there is none."""
    upper = chr(cp).upper()
    return ord(upper) if len(upper) == 1 else cp


def java_is_letter(cp):
    return unicodedata.category(chr(cp)) in ("Lu", "Ll", "Lt", "Lm", "Lo")


def is_latin_or_common(cp):
    """The old HardwareScriptLayout.isLatinOrCommon. Python has no script property, so a letter counts as
    Latin when its Unicode name says so; a non-letter never decides the question anyway."""
    if not java_is_letter(cp):
        return True
    try:
        return unicodedata.name(chr(cp)).startswith("LATIN ")
    except ValueError:
        return False


def fmt_cp(cp):
    return "U+%04X" % cp


# ── KeyboardTextSet.java: the !text/ tables ──────────────────────────────────────────────────────

JAVA_SIMPLE_ESCAPES = {"b": "\b", "t": "\t", "n": "\n", "f": "\f", "r": "\r", '"': '"', "'": "'",
                       "\\": "\\", "s": " "}


def read_java_string(src, i):
    """Parses the Java string literal opening at src[i] ('"'); returns (value, index after it)."""
    assert src[i] == '"'
    i += 1
    out = []
    while True:
        c = src[i]
        if c == '"':
            return "".join(out), i + 1
        if c == "\\":
            n = src[i + 1]
            if n == "u":
                j = i + 1
                while src[j] == "u":
                    j += 1
                out.append(chr(int(src[j:j + 4], 16)))
                i = j + 4
                continue
            if n in JAVA_SIMPLE_ESCAPES:
                out.append(JAVA_SIMPLE_ESCAPES[n])
                i += 2
                continue
            m = re.match(r"[0-7]{1,3}", src[i + 1:])
            if m:
                out.append(chr(int(m.group(0), 8)))
                i += 1 + len(m.group(0))
                continue
            raise ValueError("unknown Java escape \\%s" % n)
        out.append(c)
        i += 1


def read_java_array(src, name):
    """The elements of `NAME = { ... };` in order: str, None for null, or an identifier."""
    m = re.search(r"\b%s\s*=\s*\{" % re.escape(name), src)
    if not m:
        raise ValueError("array %s not found in %s" % (name, rel(TEXT_SET_JAVA)))
    i = m.end()
    items = []
    while True:
        while src[i] in " \t\r\n,":
            i += 1
        if src[i] == "}":
            return items
        if src[i] == '"':
            value, i = read_java_string(src, i)
            items.append(value)
            continue
        ident = re.match(r"[A-Za-z_][A-Za-z0-9_]*", src[i:])
        if not ident:
            raise ValueError("unexpected %r in array %s" % (src[i:i + 20], name))
        word = ident.group(0)
        items.append(None if word == "null" else ("IDENT", word))
        i += len(word)


class TextTables:
    """KeyboardTextSet's NAMES / TEXTS_* / LOCALES_AND_TEXTS and its lookup rules."""

    def __init__(self, path):
        src = open(path, encoding="utf-8").read()
        names = read_java_array(src, "NAMES")
        # sNameToIndexesMap is filled with put(), so for the duplicated names the last index wins.
        self.index = {}
        for i, n in enumerate(names):
            self.index[n] = i
        pairs = read_java_array(src, "LOCALES_AND_TEXTS")
        self.tables = {}
        for k in range(0, len(pairs), 2):
            locale = pairs[k]
            ident = pairs[k + 1][1]
            self.tables[locale] = read_java_array(src, ident)
        self.default = self.tables["DEFAULT"]

    def table_key_for(self, locale_string, language):
        """KeyboardTextSet.getTextsTable: the full locale string, else the language, else DEFAULT."""
        if locale_string in self.tables:
            return locale_string
        if language in self.tables:
            return language
        return "DEFAULT"

    def get_text(self, name, table_key):
        if name not in self.index:
            raise KeyError("unknown text name %s (table %s)" % (name, table_key))
        idx = self.index[name]
        table = self.tables[table_key]
        value = table[idx] if idx < len(table) else None
        if value is not None:
            return value
        if idx < len(self.default):
            return self.default[idx]
        raise KeyError("no value for %s in table %s or DEFAULT" % (name, table_key))

    def resolve(self, text, table_key):
        """KeyboardTextsSet.resolveTextReferenceInTable: expand !text/name until none is left. Null
        (None) when the result is empty, as the original."""
        if not text:
            return None
        string = text
        rounds = 0
        while True:
            rounds += 1
            if rounds >= 10:
                raise ValueError("too many !text/ indirections: " + text)
            if len(string) < 6:
                break
            sb = None
            i = 0
            n = len(string)
            while i < n:
                c = string[i]
                if string.startswith("!text/", i):
                    if sb is None:
                        sb = [string[:i]]
                    j = i + 6
                    end = j
                    # searchTextNameEnd: a name is [a-z0-9_]*.
                    while end < n and ("a" <= string[end] <= "z" or "0" <= string[end] <= "9"
                                       or string[end] == "_"):
                        end += 1
                    sb.append(self.get_text(string[j:end], table_key))
                    i = end - 1
                elif c == "\\":
                    if sb is not None:
                        sb.append(string[i:min(i + 2, n)])
                    i += 1
                elif sb is not None:
                    sb.append(c)
                i += 1
            if sb is None:
                break
            string = "".join(sb)
        return string or None


def split_key_specs(text):
    """KeySpecParser.splitKeySpecs: split on unescaped commas, keep the escapes in the tokens, skip
    empty tokens. None for an empty or absent list."""
    if not text:
        return None
    if len(text) == 1:
        return [text]
    tokens = []
    start = 0
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == ",":
            if i - start > 0:
                tokens.append(text[start:i])
            start = i + 1
        elif c == "\\":
            i += 1
        i += 1
    if n - start > 0:
        tokens.append(text[start:])
    return tokens or None


def filter_more_key_flags(tokens):
    """The old PhysicalKeySpec.filterMoreKeyFlags(moreKeys, "%"): drop the "%" placement marker."""
    if tokens is None or "%" not in tokens:
        return tokens
    return [t for t in tokens if t != "%"]


def unescape_token(token):
    """A key-spec token's backslash escapes (\\, is a comma, \\% a percent sign)."""
    out = []
    i = 0
    while i < len(token):
        if token[i] == "\\" and i + 1 < len(token):
            out.append(token[i + 1])
            i += 2
        else:
            out.append(token[i])
            i += 1
    return "".join(out)


# ── the physical-key tables, letter_layouts_tables/pkbd_*.xml ──────────────────────────────────────────────────

class PkbdTable:
    """The old PhysicalKeySpecTable as KeyboardXMLParser filled it for one subtype: label -> lists."""

    def __init__(self, file_name, layout_set, language, table_key, texts):
        self.file_name = file_name
        self.more_keys = {}
        self.multitap = {}
        self.char_map = {}
        self.order = []
        root = ET.parse(os.path.join(TABLES_DIR, file_name + ".xml")).getroot()
        ext = root.find("PhysicalKeyboardExtension")
        self._walk(ext, layout_set, language, table_key, texts)

    def _matches(self, case, layout_set, language):
        for attr, value in (("keyboardLayoutSet", layout_set), ("languageCode", language)):
            wanted = case.get(LATIN_NS + attr)
            if wanted is not None and value not in wanted.split("|"):
                return False
        for attr in case.attrib:
            local = attr.split("}")[-1]
            if local not in ("keyboardLayoutSet", "languageCode"):
                raise ValueError("%s: unhandled <case> attribute %s" % (self.file_name, local))
        return True

    def _walk(self, element, layout_set, language, table_key, texts):
        for child in element:
            if child.tag == "PhysicalKey":
                self._add(child, table_key, texts)
            elif child.tag == "switch":
                for case in child:
                    if case.tag == "default" or (case.tag == "case" and
                                                 self._matches(case, layout_set, language)):
                        self._walk(case, layout_set, language, table_key, texts)
                        break
            else:
                raise ValueError("%s: unexpected <%s>" % (self.file_name, child.tag))

    def _add(self, key, table_key, texts):
        def attr(name):
            return key.get(LATIN_NS + name)

        label = texts.resolve(attr("keySpec"), table_key)
        if not label:
            raise ValueError("%s: a PhysicalKey with an empty keySpec" % self.file_name)
        more = filter_more_key_flags(split_key_specs(texts.resolve(attr("moreKeys"), table_key)))
        multitap = split_key_specs(texts.resolve(attr("multitapKeys"), table_key))
        char_map = split_key_specs(texts.resolve(attr("characterMapKeys"), table_key))
        if label not in self.order:
            self.order.append(label)
        # addPhysicalKeySpec: each list is put only when present, so a later entry for the same
        # label replaces just the lists it has; the Shift legend falls back to the multitap list.
        if more is not None:
            self.more_keys[label] = more
        if multitap is not None:
            self.multitap[label] = multitap
        shift = char_map if char_map is not None else multitap
        if shift is not None:
            self.char_map[label] = shift

    def shift_legend(self, label):
        """The old KeyboardSwitcher.getPhysicalShiftLetter: the first characterMapKeys entry, or None."""
        keys = self.char_map.get(label)
        return keys[0] if keys else None


def physical_keyboard_of(layout_set):
    """The keyboard KeyboardBuilder builds for the physical keys of a layout set: its alphabetPkb
    element, else (the builder's fallback) its on-screen alphabet. Returns the file and whether it
    is kbd_alphabet_pkb, the one keyboard that carried the physical-key tables."""
    root = ET.parse(os.path.join(RES_XML, "keyboard_layout_set_%s.xml" % layout_set)).getroot()
    elements = {}
    for element in root.findall("Element"):
        elements[element.get(LATIN_NS + "elementName")] = \
            element.get(LATIN_NS + "elementKeyboard").replace("@xml/", "")
    kbd = elements.get("alphabetPkb") or elements.get("alphabet")
    return kbd, kbd == "kbd_alphabet_pkb"


# ── the engine's hardware layouts, assets/kdb/<name>_pkb.xml ─────────────────────────────────────

AREA = re.compile(r"<area>(.*?)</area>", re.S)
KEY = re.compile(r"<key\b([^>]*)/>")
ATTRIBUTE = re.compile(r"([A-Za-z0-9_]+)=\"([^\"]*)\"")
CHOSEONG_TO_COMPATIBILITY = [0x3131, 0x3132, 0x3134, 0x3137, 0x3138, 0x3139, 0x3141, 0x3142,
                             0x3143, 0x3145, 0x3146, 0x3147, 0x3148, 0x3149, 0x314A, 0x314B,
                             0x314C, 0x314D, 0x314E]


def to_compatibility_jamo(cp):
    if 0x1100 <= cp <= 0x1112:
        return CHOSEONG_TO_COMPATIBILITY[cp - 0x1100]
    if 0x1161 <= cp <= 0x1175:
        return 0x314F + (cp - 0x1161)
    return cp


def dp(value):
    try:
        return int(value[:-2].strip() if value.endswith("dp") else value.strip())
    except ValueError:
        return 0


def key_code_at(row, column):
    """The old HardwareScriptLayout.keyCodeAt: the KEYCODE_ name at a QWERTY grid position, or None."""
    index = column - 1 if row == 2 else column
    letters = KEYCODE_ROWS[row]
    if index < 0 or index >= len(letters):
        return None
    return "KEYCODE_" + letters[index]


class ScriptLayout:
    """The old HardwareScriptLayout.parse, rule for rule: cells by key code, the extra key at row 3
    column 8, and whether the file is a script layout at all."""

    def __init__(self, path):
        self.path = path
        self.cells = {}
        self.extra = None
        self.script = False
        self.nordic_form_keys = 0
        xml = open(path, encoding="utf-8").read()
        for row, area in enumerate(AREA.finditer(xml)):
            if row >= len(KEYCODE_ROWS):
                continue
            for key in KEY.finditer(area.group(1)):
                attributes = dict(ATTRIBUTE.findall(key.group(1)))
                if attributes.get("keyType") == "function":
                    continue
                if "keyCodes" not in attributes:
                    continue
                codes = [to_compatibility_jamo(int(t[2:] if t[:2] in ("0x", "0X") else t, 16))
                         for t in (s.strip() for s in attributes["keyCodes"].split(",")) if t]
                if not codes:
                    continue
                if "keyLabel" in attributes:
                    # The Latin KDBs' "keyLabel + keyCodes" form: parse() ignores the label and
                    # takes the first code as the letter. No script layout has one today.
                    self.nordic_form_keys += 1
                width = dp(attributes.get("keyWidth", ""))
                if width <= 0:
                    width = 108
                if "keyLeft" not in attributes:
                    continue
                left = dp(attributes["keyLeft"])
                column = (left + width // 2) // width
                letter = codes[0]
                if java_is_letter(letter) and not is_latin_or_common(letter):
                    self.script = True
                code = key_code_at(row, column)
                if code is not None:
                    self.cells[code] = codes
                elif row == 2 and column == 8:
                    self.extra = codes


def kdb_letters(name):
    """Every letter a key of assets/kdb/<name>_pkb.xml carries, primary first, by key code: the
    owned loader's reading (kdb_load_xml.c key_codes_of). A single ASCII keyLabel is the primary,
    in lower case, and a keyCodes list beside it the alternates; otherwise keyCodes holds them all.
    The shipped file, or the reference copy of one the app now builds."""
    path = kdb_path(name)
    xml = open(path, encoding="utf-8").read()
    letters = {}
    for row, area in enumerate(AREA.finditer(xml)):
        if row >= len(KEYCODE_ROWS):
            continue
        for key in KEY.finditer(area.group(1)):
            attributes = dict(ATTRIBUTE.findall(key.group(1)))
            if attributes.get("keyType") == "function" or "keyLeft" not in attributes:
                continue
            codes = [int(t[2:] if t[:2] in ("0x", "0X") else t, 16)
                     for t in (s.strip() for s in attributes.get("keyCodes", "").split(",")) if t]
            label = attributes.get("keyLabel", "")
            if len(label) == 1 and label.isascii() and label.isalpha():
                codes = [ord(label.lower())] + codes
            if not codes:
                continue
            width = dp(attributes.get("keyWidth", "")) or 108
            column = (dp(attributes["keyLeft"]) + width // 2) // width
            code = key_code_at(row, column)
            if code is None and row == 2 and column == 8:
                code = "KEYCODE_4"
            if code is not None:
                letters[code] = [to_compatibility_jamo(c) for c in codes]
    return path, letters


def add_engine_keys(doc, language):
    """Gives each key of [doc] the letters the KDB its keyboard's engine loads carries on that key
    beyond the ones the key already names (its letter, Shift legend and double-tap letters)."""
    path, letters = kdb_letters(ENGINE_KDB.get(language, ENGINE_KDB_DEFAULT))
    added = 0
    for key in doc.keys:
        named = [ord(key.key_spec)]
        if key.character_map_keys:
            named.append(ord(key.character_map_keys))
        named += [ord(m) for m in key.multitap_keys if len(m) == 1]
        extra = []
        for c in letters.get(key.code, []):
            if c not in named and c not in extra:
                extra.append(c)
        key.engine_keys = [chr(c) for c in extra]
        added += len(extra)
    if added:
        doc.sources.append("engine letters %s" % rel(path))


