/* Trace-record sessionTag @rec+0x28 is the loaded KDB's content stamp (NKL +0x0c), per KDB
 * (uneven 0xBB786DC7, uniform-108 0xAF5B3D8D, uniform-150 0x27BE5ACF). This is a fallback only. */
#define ET9_SESSION_TAG  0xBB786DC7u
#define MAX_SAMPLES      2560   /* >= the engine's 2499 cap (ET9_TRACE_CAP) */

#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
static ET9U32 g_pst_calls;   /* ProcessStoredTouch calls this gesture; see the interpose below */
#endif

/* Per-gesture accumulation buffer (process-global). */
static ET9KdbSample g_buf[MAX_SAMPLES];
static ET9U32       g_n;
static ET9U32       g_startT;
static float        g_startX, g_startY;

/* Which contact owns the single path buffer (owner filtering; the recognizer is single-path):
 *   TouchStart  newest contact wins (the gesture arbiter's chained-flick contract); the
 *               abandonment is counted and logged.
 *   TouchMove   samples from a non-owner are dropped.
 *   TouchEnd    a non-owner's end neither appends nor runs the recognizer.
 *   TouchCancel clears regardless of touchId (the arbiter's contract and the unstick path).
 * Filtering applies only while a session is live, keeping the out-of-order tolerances pinned by
 * touch_abi_selftest.c section 6. */
static int    g_session_live;      /* a TouchStart has claimed the buffer */
static ET9U64 g_session_id;        /* the owning touchId; valid while g_session_live */
static ET9U32 g_foreign_drops;     /* contacts rejected/abandoned because they are not the owner */

ET9U32 xt9kdb_foreign_contact_drops(void) { return g_foreign_drops; }

/* In-band recognizer health: TouchEnd always returns ET9STATUS_NONE (the engine's dispatcher
 * hardcodes 0), so failures are counted here, monotonic, surfaced via Xt9KdbVariant.
 *   unavailable: no recognizer reachable (no context, or the engine symbol did not bind).
 *   failures:    a recognizer ran and returned non-NONE.
 * A DIFF build never reaches a recognizer, so it counts neither. */
static ET9U32 g_rec_unavailable;
static ET9U32 g_rec_failures;
ET9U32 xt9kdb_recognizer_unavailable(void) { return g_rec_unavailable; }
ET9U32 xt9kdb_recognizer_failures(void)    { return g_rec_failures; }

/* 1 when `touchId` may not touch the live session. */
static int foreign_contact(ET9U64 touchId) {
    return g_session_live && touchId != g_session_id;
}

/* Deposit-ranked gesture word, filled in owned_pst_v2 and taken once per seq. Outside the
 * CUTOVER guard because xt9kdb_variant_jni.c calls it in both modes (DIFF never fills it). */
static char   g_gesture_word[80];
static ET9U32 g_gesture_word_seq;   /* rank-snapshot seq this word belongs to; 0 = none */

int xt9kdb_take_gesture_word(ET9U32 seq, char* out, int outsz) {
    if (!out || outsz <= 0) return 0;
    if (g_gesture_word_seq == 0 || g_gesture_word_seq != seq || !g_gesture_word[0]) return 0;
    int i = 0; for (; i < outsz - 1 && g_gesture_word[i]; i++) out[i] = g_gesture_word[i];
    out[i] = 0;
    g_gesture_word_seq = 0;            /* consume-once */
    return i;
}

/* Read-only view of the raw-sensor path (for kdb_decode_legacy.c, DIFF/host builds only). */
const ET9KdbSample* xt9kdb_stored_path(ET9U32* count) {
    if (count) *count = g_n;
    return g_buf;
}

ET9STATUS XT9KDB(SetTraceInput)(ET9KDBInfoPtr ctx, ET9BOOL on) { (void)ctx;(void)on; g_n = 0; g_session_live = 0; return ET9STATUS_NONE; }
ET9STATUS XT9KDB(ClearTraceInput)(ET9KDBInfoPtr ctx)          { (void)ctx; g_n = 0; g_session_live = 0; return ET9STATUS_NONE; }

/* Engine point admission (ET9KDB_TouchMove @0xbc664): a point within 1.0px of the previous sample
 * in both axes only updates its timestamp. Hard cap 2499. */
#define ET9_TRACE_CAP 2499
static void push(float x, float y, ET9U32 t) {
    if (g_n) {
        float dx = x - g_buf[g_n-1].x, dy = y - g_buf[g_n-1].y;
        if (dx > -1.0f && dx < 1.0f && dy > -1.0f && dy < 1.0f) {
            g_buf[g_n-1].timestamp = t;   /* near-duplicate: merge (timestamp only) */
            return;
        }
    }
    if (g_n < ET9_TRACE_CAP && g_n < MAX_SAMPLES) {
        g_buf[g_n].x = x; g_buf[g_n].y = y; g_buf[g_n].timestamp = t; g_n++;
    }
}

/* Call this, not the exported ET9KDB_ProcessTrace, which the engine interposes. */
static ET9STATUS process_trace_impl(ET9KDBInfoPtr ctx);

/* Accumulate one batch (the shim sends count=1). nStart is not a start index: the engine zeroes
 * its own index at 0xbbde0. */
static void push_batch(const float* xs, const float* ys, const ET9U32* ts, ET9U32 count) {
    for (ET9U32 i = 0; i < count; i++)
        push(xs ? xs[i] : 0.0f, ys ? ys[i] : 0.0f, ts ? ts[i] : 0u);
}

ET9STATUS XT9KDB(TouchStart)(ET9KDBInfoPtr ctx, ET9U64 touchId, const float* xs, const float* ys,
                             const ET9U32* ts, ET9U32 count, ET9U32 nStart) {
    (void)nStart;
    /* Re-publish this ctx's model and scale to the ctx-less globals: the spellchecker's engine
     * may have loaded another KDB, and downstream consumers must see the gesture owner's. */
    { const ET9KdbLoaded* m = xt9kdb_model_for_ctx(ctx); if (m) xt9kdb_set_model(m); }
    xt9kdb_publish_ctx_scale(ctx);
    /* A second contact takes the buffer (newest wins); logged to tell edge brushes from chained
     * flicks in a TRACEPT dump. */
    if (foreign_contact(touchId)) {
        g_foreign_drops++;
        XT9KDB_LOGI("TouchStart: contact %llu abandons in-flight contact %llu (n=%u)",
                    (unsigned long long)touchId, (unsigned long long)g_session_id, g_n);
    }
    g_session_live = 1;
    g_session_id   = touchId;
    g_n = 0;
#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
    g_pst_calls = 0;              /* per-gesture, so the PSt log stays readable */
#endif
    if (count && xs && ys) { g_startX = xs[0]; g_startY = ys[0]; g_startT = ts ? ts[0] : 0u; }
    push_batch(xs, ys, ts, count);
    XT9KDB_LOGD("TouchStart n=%u x=%.1f y=%.1f t=%u", g_n, (double)g_startX, (double)g_startY, g_startT);
    return ET9STATUS_NONE;
}

