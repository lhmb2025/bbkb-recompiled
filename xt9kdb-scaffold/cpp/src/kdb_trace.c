/* CUTOVER: store the accumulated gesture into the result block byte-exactly for the blob's recognizer.
 * (DIFF/scratch keeps decode_scratch + XT9OWNED separate; this path owns the storage, delegates scoring.) */
/* The exported name is interposable: libkb.so carries an R_AARCH64_JUMP_SLOT for
 * ET9KDB_ProcessTrace, and the blob (loaded first, and NOT UNDEF'd for this symbol -- it is absent
 * from elf_cutover.py's CONTRACT) wins global symbol lookup. So an internal call to the EXPORTED
 * name lands in the blob, which then reads gesture state we intercepted and never populated ->
 * SIGSEGV in ET9KDB_ProcessTrace+308, device-confirmed 2026-08-03.
 *
 * Callers inside this module must therefore use process_trace_impl, never XT9KDB(ProcessTrace).
 * Same class of defect as ctx+0x5a: owning half a subsystem means owning the seams between the
 * halves. */
/* Hand the accumulated path to the blob's OWN recognizer.
 *
 * Whole-.text scan (355,836 instructions, skipdata=True) settled the architecture: the recognition
 * dispatcher at 0x3d9c8 has exactly 15 call sites and EVERY one is inside
 * ET9KDB_TouchStart/Move/End/EndAll/Cancel/TimeOut. Nothing anywhere polls the result block for
 * finished records. Recognition is a synchronous PUSH from the Touch* entry points -- four of which
 * the cutover hands to us -- so once we own them, nobody kicks the scorer and a byte-perfect record
 * is inert. That is why months of record byte-parity work changed nothing: it was perfecting data
 * no code reads.
 *
 * ET9KDB_ProcessTrace @0xca4cc is the clean way back in: a complete standalone recognizer that
 * builds record[0] itself, arms the lock and drives ProcessStoredTouch. It has ZERO callers inside
 * the blob, so it is purely host-facing and safe for us to call.
 *
 * GATE (0xca588/0xca58c): it loads result+0x374 and bails with 0x66 unless that is ZERO. Our old
 * store_trace_record wrote 1 there, which is why it must be gone rather than merely unused --
 * nothing ever decrements it, so a single stale write disables the recognizer permanently. */

