/* kdb_trace.c — gesture (trace) input path.
 *
 * ARCHITECTURE (settled 2026-08-03 by whole-.text scan + stock-blob A/B; supersedes everything
 * this header used to claim).
 *
 * Recognition is a synchronous PUSH, not a poll. The dispatcher at 0x3d9c8 has exactly 15 call
 * sites in the blob and EVERY one is inside ET9KDB_TouchStart/TouchMove/TouchEnd/TouchEndAll/
 * TouchCancel/TouchTimeOut. Nothing scans the result block for finished records. The cutover hands
 * four of those six entry points to us, so once we own them nobody kicks the scorer — and a
 * byte-perfect trace record is inert. That is why successive rounds of record byte-parity work
 * (header fields, session tag, flags, state) changed nothing on device: they were perfecting data
 * that no code reads.
 *
 * So this module no longer writes the result block at all. TouchStart/Move/End accumulate the path,
 * and TouchEnd hands it to ET9KDB_ProcessTrace @0xca4cc — a complete standalone recognizer that
 * builds record[0] itself, arms the dispatch lock, and drives ProcessStoredTouch. It has ZERO
 * callers inside the blob (pure host-facing API), so calling it is safe from reentrancy and, since
 * it is absent from elf_cutover.py's CONTRACT, the blob's definition is the one we reach.
 *
 * TRAP: ProcessTrace bails with 0x66 unless result+0x374 is ZERO (0xca588/0xca58c), and nothing
 * ever decrements that field. The old owned writer set it to 1, permanently disabling the only
 * working entry point. Never write the result block from here again.
 *
 * Corrected facts the old header got wrong:
 *   - record state(+0x44)==2 means "finger down" (TouchStart sets it before the first sample),
 *     NOT "finalized/ready for recognition".
 *   - result+0x374 is an ACTIVE-TOUCH COUNT, not a pending-record count.
 *   - sample[0] is at record+0x50, not +0x5c.
 *   - Touch* take ARRAYS with a count, not scalar x/y/t — see et9kdb.h for the derivation.
 *
 * The live owned decode is owned_pst_v2 (kdb_decode.c segmentation + ambiguous smart-touch sets).
 * The superseded first-cut decoder that used to live here (decode_keyseq + the AW commit hooks,
 * which powered the W3a XT9OWNED scratch comparison) now lives in kdb_decode_legacy.c and is
 * compiled only in the DIFF branch and the host test build -- it is not in the shipped libkb.so.
 */
