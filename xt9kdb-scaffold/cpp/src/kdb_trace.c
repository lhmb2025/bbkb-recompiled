/* The owned-recall index stores word indices in ET9U16 and sizes g_rc_list/g_rc_len at 65536;
 * a larger table would silently drop its tail from recall (the 32768->59878 regression). */
_Static_assert(kFreqCountEn <= 65536, "kFreqCountEn exceeds the u16 recall-index cap (65536)");

/* W4: candidate == echo with exactly ONE letter doubled (helo->hello, cofe->coffe)?
 * Dwell EMISSION at decode time lost the natural-mix gate (short-word over-fire,
 * -3.1 net top-1), but the pools already RECALL most double words — the loss was in
 * ranking, where the flat-geometry lookalike (help vs hello) wins on frequency. This
 * targeted bonus fixes doubles where they actually break, with zero decode risk. */
static int is_double_expansion(const char* cand, const char* echo) {
    size_t cl = strlen(cand), el = strlen(echo);
    if (cl != el + 1) return 0;
    for (size_t i = 0; i < el; i++) {
        if (cand[i] != echo[i]) return 0;
        if (cand[i + 1] == cand[i] && !strcmp(cand + i + 2, echo + i + 1)) return 1;
    }
    return 0;
}

/* ---- dwell-evidence double support (VKB doubles workstream, 2026-08-28) --------------------
 * On the VKB corpus the user measurably PAUSES on a doubled letter's key mid-swipe (interior
 * doubles median 567ms vs 233ms plain pass-through; end doubles 589 vs 205), so "time spent
 * within the doubled key's radius" is direct evidence for the double candidate — the signal
 * W4 could not find on the CKB. dwell_at_key sums inter-sample time inside radius r around
 * (kx,ky) over the deposited (authored-space) path; dbl_dwell_support returns 1 iff the
 * candidate has a doubled a-z letter whose key shows >= thr_ms of dwell. */
static float dwell_at_key(const Xt9DecPt* sp, ET9U32 n, float kx, float ky, float r) {
    /* MAX CONTIGUOUS stay, not total: a deliberate double-pause is one continuous visit. A long
     * trace can pass near a key several times and SUM past any threshold (measured: proper's
     * path crediting perrier's rr), but per-visit time stays low — contiguous cuts the corpus
     * false-fire rate 9% -> 1.5% at thr=400 while keeping 88% of true doubles. */
    float best = 0.0f, cur = 0.0f;
    for (ET9U32 i = 1; i < n; i++) {
        float dx = sp[i].x - kx, dy = sp[i].y - ky;
        if (dx * dx + dy * dy <= r * r) {
            cur += (float)(sp[i].t - sp[i - 1].t);
            if (cur > best) best = cur;
        } else cur = 0.0f;
    }
    return best;
}
static int dbl_dwell_support(const ET9KdbLoaded* m, const Xt9DecPt* sp, ET9U32 n,
                             const char* w, int thr_ms) {
    if (!m || !sp || n < 2) return 0;
    for (int i = 1; w[i]; i++) {
        char a = w[i], b = w[i - 1];
        if (a >= 'A' && a <= 'Z') a += 32;
        if (b >= 'A' && b <= 'Z') b += 32;
        if (a != b || a < 'a' || a > 'z') continue;
        for (ET9U16 k = 0; k < m->keyCount; k++) {
            if (m->keys[k].keyCode != (ET9U16)a) continue;
            float r = 0.65f * (float)(m->keys[k].right - m->keys[k].left);
            if (dwell_at_key(sp, n, (float)m->keys[k].cx, (float)m->keys[k].cy, r) >= (float)thr_ms)
                return 1;
            break;
        }
    }
    return 0;
}

/* W6: LIVE LDB frequency of selection-list candidate `gi`, straight from the engine
 * (language-independent, exact vocab-parity, no wordfreq table). Chain recovered by RE
 * (docs/re/): L = *(P)+0x8 (alphaGetSelectionListWord@0x1cf20), the PUBLIC
 * ET9AWSelLstGetWord@0xef7e4(L,&entry,gi) returns a ptr to the internal 616B entry, and
 * the word's frequency is the float32 at entry+0x124 (validated: done 2.4M > some 1.7M >
 * dome 6.9K > helo 1.0). Returns <0 if unavailable (caller falls back to the table). */
/* foff = which frequency field of the 616B entry to use as the prior (W6-C). 0x124 (default)
 * is the LDB+DLM frequency the ranker ships; 0x12c is a larger, related value (~2-3x higher),
 * the candidate CONTEXT-scaled frequency. Selectable (debug.et9.freqoff, read by the caller)
 * so the paragraph-corpus context A/B is a one-prop flip. Context is NOT validatable on
 * isolated-word replays (needs real sentences), so default stays 0x124 until the paragraph
 * gate. */
static float xt9_live_freq(uintptr_t blob_base, void* P, int gi, int foff) {
    if (!P || !blob_base) return -1.0f;
    void* alpha = *(void**)P;
    if (!alpha) return -1.0f;
    typedef int (*fn_slg)(void*, void**, int);
    fn_slg slg = (fn_slg)(blob_base + 0xef7e4u);
    void* ep = 0;
    if (slg((char*)alpha + 0x8, &ep, gi) != 0 || !ep) return -1.0f;
    if (foff != 0x124 && foff != 0x128 && foff != 0x12c) foff = 0x124;
    return *(float*)((char*)ep + foff);
}

/* W6 locale gate: active LDB language via ET9AWLdbGetActiveLanguage@0xd4de0(L, &out),
 * L = *(P)+0x8. Returns the ET9 primary-language id, or -1 if unavailable. English variants
 * enable the English-lexicon pieces (W5 owned recall + the wordfreq-table echo/double
 * heuristics); the LIVE-frequency pool prior is language-independent and always on. */
static int xt9_active_lang(uintptr_t blob_base, void* P) {
    if (!P || !blob_base) return -1;
    void* alpha = *(void**)P;
    if (!alpha) return -1;
    typedef int (*fn_gal)(void*, ET9U32*);
    fn_gal gal = (fn_gal)(blob_base + 0xd4de0u);
    ET9U32 lang = 0;
    if (gal((char*)alpha + 0x8, &lang) != 0) return -1;
    return (int)lang;
}

/* zipf*10 of a lowercase word (0 = unknown => rare/nonword). Binary search over the
 * generated table; NONWORD threshold used by the ranker = 28 (zipf 2.8). */
static int freq_zipf10(const char* w) {
    int lo = 0, hi = kFreqCountEn - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        int c = strcmp(w, kFreqWordsEn[mid]);
        if (c == 0) return (int)kFreqZipfEn[mid];
        if (c < 0) hi = mid - 1; else lo = mid + 1;
    }
    return 0;
}

/* raw LDB rank of a lowercase word (INT_MAX = unknown => treat as rarest). Used ONLY to break an
 * exact score tie toward the more-common (lower-rank) word — pool(1894) over poll(1895), which are
 * geometrically identical as swipes and quantize to the same zipf*10. */
static int freq_rank(const char* w) {
    int lo = 0, hi = kFreqCountEn - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        int c = strcmp(w, kFreqWordsEn[mid]);
        if (c == 0) return (int)kFreqRankEn[mid];
        if (c < 0) hi = mid - 1; else lo = mid + 1;
    }
    return 0x7fffffff;
}

/* ==== W5: trace-native owned recall (plan §3 W5 / §12) =========================================
 * SHARK2-style lexicon recall over the RAW trace: prune the 30k-word table by start/end
 * anchor keys (top-3 nearest each) + ideal-path-vs-arc length ratio, score survivors with
 * xt9kdb_rank_score, and MERGE with the AW tap-corrector pool (union — recall can only rise;
 * the W3/W4 blend arbitrates both pools with identical scoring). Pruning validated offline on
 * the 69 real traces: intended word survives 69/69, median 167 survivors, p90 ~1.2k.
 * This is the piece the discretize->correct pipeline could never provide: pass-through
 * letters (very's r), zigzag drops (question), and corner classes are geometrically invisible
 * in a committed skeleton but alive in the raw trace. */

#define RC_MAX_SCORE 1500      /* survivor cap per gesture (p90 ~1.2k; log when hit) */
#define RC_TOP 8               /* candidates handed to the blend */

static ET9U16 g_rc_list[65536];          /* word indices grouped by (first,last) letter (cap >= table size) */
static ET9U32 g_rc_off[26][27];          /* [f][l] start into g_rc_list; [f][26] = end */
static int    g_rc_built = 0;
static float  g_rc_len[65536];           /* per-word ideal path length (authored space)  */
static const ET9KdbLoaded* g_rc_len_model = 0;
static float  g_rc_kx[26], g_rc_ky[26];  /* letter -> key center, current model */

/* (first,last) bucket of a table word, or 0 if the word does not bucket (shorter than two
 * characters, or an end letter outside a..z). Matches the reference builder's implicit filter:
 * there `a - 'a' != f` never matches for a char outside a..z, so such words were never emitted. */
static int rc_word_bucket(const char* w, int* f, int* l) {
    size_t len = strlen(w);
    if (len < 2) return 0;
    char a = w[0], b = w[len - 1];
    if (a < 'a' || a > 'z' || b < 'a' || b > 'z') return 0;
    *f = a - 'a'; *l = b - 'a';
    return 1;
}

/* REFERENCE builder: the original O(26*26*N) formulation -- one full rescan of the table per
 * letter pair, ~40M strlen calls for the 59,878-word table. Measured 160 ms on the emulator and
 * 1-2 s on the KEY2, paid ON THE MAIN THREAD by the first gesture of the process (touchEnd ->
 * ProcessTrace(OWNED) -> rc_recall). Kept only as the oracle for xt9kdb_recall_index_selfcheck. */
static ET9U32 rc_build_index_reference(ET9U16* list, ET9U32 off[26][27]) {
    ET9U32 n = 0;
    for (int f = 0; f < 26; f++) {
        for (int l = 0; l < 26; l++) {
            off[f][l] = n;
            for (int i = 0; i < kFreqCountEn && n < 65536; i++) {
                const char* w = kFreqWordsEn[i];
                size_t len = strlen(w);
                if (len < 2) continue;
                char a = w[0], b = w[len - 1];
                if (a - 'a' != f || b - 'a' != l) continue;
                list[n++] = (ET9U16)i;
            }
        }
        off[f][26] = n;
    }
    return n;
}

/* LIVE builder: counting sort, O(N). One pass sizes the 676 buckets, prefix sums lay them out
 * contiguously in (first,last) order, one pass places the indices. Within a bucket the words stay
 * in ascending table index -- exactly what the reference emitted -- which the recall loop relies
 * on twice: its RC_MAX_SCORE survivor cap decides WHICH words get scored by bucket order, and its
 * top-RC_TOP insertion keeps the earlier word on an equal geometry score. The selfcheck below
 * asserts the two builders agree byte for byte. */
static ET9U32 rc_build_index_into(ET9U16* list, ET9U32 off[26][27]) {
    ET9U32 cnt[26][26];
    memset(cnt, 0, sizeof cnt);
    for (int i = 0; i < kFreqCountEn && i < 65536; i++) {
        int f, l;
        if (rc_word_bucket(kFreqWordsEn[i], &f, &l)) cnt[f][l]++;
    }
    ET9U32 n = 0;
    ET9U32 cur[26][26];
    for (int f = 0; f < 26; f++) {
        for (int l = 0; l < 26; l++) { off[f][l] = n; cur[f][l] = n; n += cnt[f][l]; }
        off[f][26] = n;
    }
    for (int i = 0; i < kFreqCountEn && i < 65536; i++) {
        int f, l;
        if (rc_word_bucket(kFreqWordsEn[i], &f, &l)) list[cur[f][l]++] = (ET9U16)i;
    }
    return n;
}

static void rc_build_index(void) {
    if (g_rc_built) return;
    ET9U32 n = rc_build_index_into(g_rc_list, g_rc_off);
    g_rc_built = 1;
    XT9KDB_LOGI("ownRecall: index built, %u bucketed words", n);
}

/* Debug/host selfcheck: the live O(N) builder must reproduce the reference builder byte for byte
 * (bucket offsets AND per-bucket order). corrupt != 0 flips one reference entry first, so the
 * negative control proves the comparison can fail. Returns 0 on match; 1 = word-count mismatch,
 * 2 = offset-table mismatch, 3 = list mismatch, -1 = out of memory. Scratch is heap-allocated
 * (2 x 128 KB) and freed; the live index is not touched. */
int xt9kdb_recall_index_selfcheck(int corrupt, unsigned* out_words) {
    ET9U16* refList = (ET9U16*)malloc(65536 * sizeof(ET9U16));
    ET9U16* newList = (ET9U16*)malloc(65536 * sizeof(ET9U16));
    if (!refList || !newList) { free(refList); free(newList); return -1; }
    ET9U32 refOff[26][27], newOff[26][27];
    memset(refList, 0, 65536 * sizeof(ET9U16));
    memset(newList, 0, 65536 * sizeof(ET9U16));
    ET9U32 nr = rc_build_index_reference(refList, refOff);
    ET9U32 nn = rc_build_index_into(newList, newOff);
    if (corrupt && nr > 1) refList[nr / 2] ^= 1;   /* one wrong word index mid-table */
    int rc = 0;
    if (nr != nn) rc = 1;
    else if (memcmp(refOff, newOff, sizeof refOff) != 0) rc = 2;
    else if (memcmp(refList, newList, nr * sizeof(ET9U16)) != 0) rc = 3;
    if (out_words) *out_words = (unsigned)nn;
    free(refList); free(newList);
    return rc;
}

static void rc_refresh_model(const ET9KdbLoaded* m) {
    if (g_rc_len_model == m) return;
    for (int c = 0; c < 26; c++) { g_rc_kx[c] = -1.0f; g_rc_ky[c] = -1.0f; }
    for (ET9U16 i = 0; i < m->keyCount; i++) {
        ET9U16 kc = m->keys[i].keyCode;
        if (kc >= 'a' && kc <= 'z') { g_rc_kx[kc - 'a'] = (float)m->keys[i].cx; g_rc_ky[kc - 'a'] = (float)m->keys[i].cy; }
    }
    for (int i = 0; i < kFreqCountEn && i < 65536; i++) {
        const char* w = kFreqWordsEn[i];
        float L = 0.0f, px = -1.0f, py = -1.0f;
        for (const char* c = w; *c; c++) {
            if (*c < 'a' || *c > 'z') continue;              /* apostrophes ride along */
            float x = g_rc_kx[*c - 'a'], y = g_rc_ky[*c - 'a'];
            if (x < 0.0f) { L = -1.0f; break; }              /* letter not on this KDB */
            if (px >= 0.0f) L += sqrtf((x - px) * (x - px) + (y - py) * (y - py));
            px = x; py = y;
        }
        g_rc_len[i] = L;
    }
    g_rc_len_model = m;
    XT9KDB_LOGI("ownRecall: ideal lengths cached for model %ux%u",
                (unsigned)m->authoredWidth, (unsigned)m->authoredHeight);
}

/* Recall candidates for the CURRENT snapshot. Returns count (<= RC_TOP); fills word indices
 * and geometry scores, best first. */
static int rc_recall(const Xt9DecPt* sp, ET9U32 n, const Xt9DecParams* p,
                     int* outIdx, float* outGeo) {
    if (n < 3) return 0;
    rc_build_index();
    rc_refresh_model(g_kdb_model);
    /* The caller (owned_pst_v2) already mapped the path into AUTHORED space via
     * xt9kdb_sensor_to_authored — do NOT re-apply it here (the SetKeyboardSize stretch is not
     * idempotent; a second application would double-scale VKB paths). */
    float ax0 = sp[0].x, ay0 = sp[0].y;
    float ax1 = sp[n - 1].x, ay1 = sp[n - 1].y;
    ET9SYMB s0[8], s1[8]; ET9U8 fq[8];
    int n0 = xt9kdb_point_to_candidates(g_kdb_model, ax0, ay0, s0, fq, 3);
    int n1 = xt9kdb_point_to_candidates(g_kdb_model, ax1, ay1, s1, fq, 3);
    if (n0 <= 0 || n1 <= 0) return 0;
    float arc = 0.0f, pxx = 0.0f, pyy = 0.0f;
    for (ET9U32 i = 0; i < n; i++) {
        float ax = sp[i].x, ay = sp[i].y;   /* already authored (see above) */
        if (i) arc += sqrtf((ax - pxx) * (ax - pxx) + (ay - pyy) * (ay - pyy));
        pxx = ax; pyy = ay;
    }
    /* score survivors, keep top RC_TOP by geometry */
    float bestGeo[RC_TOP]; int bestIdx[RC_TOP]; int nb = 0;
    int scored = 0, capped = 0;
    for (int a = 0; a < n0 && !capped; a++) {
        if (s0[a] < 'a' || s0[a] > 'z') continue;
        int f = s0[a] - 'a';
        for (int b = 0; b < n1 && !capped; b++) {
            if (s1[b] < 'a' || s1[b] > 'z') continue;
            int l = s1[b] - 'a';
            for (ET9U32 k = g_rc_off[f][l]; k < g_rc_off[f][l + 1]; k++) {
                int wi = g_rc_list[k];
                float L = g_rc_len[wi];
                if (L < 0.0f) continue;
                if (arc >= 40.0f) {
                    if (!(0.45f * arc <= L + 80.0f && L + 80.0f <= 1.9f * arc + 160.0f)) continue;
                } else if (L > 200.0f) continue;
                if (++scored > RC_MAX_SCORE) { capped = 1; break; }
                float g = xt9kdb_rank_score(g_kdb_model, p, sp, n, kFreqWordsEn[wi], 0);
                if (nb < RC_TOP || g < bestGeo[nb - 1]) {
                    int q = (nb < RC_TOP) ? nb++ : (RC_TOP - 1);
                    while (q > 0 && bestGeo[q - 1] > g) {
                        bestGeo[q] = bestGeo[q - 1]; bestIdx[q] = bestIdx[q - 1]; q--;
                    }
                    bestGeo[q] = g; bestIdx[q] = wi;
                }
            }
        }
    }
    if (capped) XT9KDB_LOGF("ownRecall: survivor cap hit (%d scored)", scored);
    for (int i = 0; i < nb; i++) { outIdx[i] = bestIdx[i]; outGeo[i] = bestGeo[i]; }
    return nb;
}

/* Trace-record sessionTag @rec+0x28 = the LOADED KDB's CONTENT CHECKSUM (== NKL header +0x0c), copied
 * per gesture. It is per-KDB, not a constant: uneven-band KDB = 0xBB786DC7, uniform-108 KDB = 0xAF5B3D8D,
 * uniform-150 = 0x27BE5ACF (probe captures 2026-07-05). The 0xBB786DC7 below is the UNEVEN KDB's checksum
 * (our current live layout) and is a FALLBACK only. TODO(cutover): source the tag from the live NKL+0x0c
 * instead of this constant (checksum algorithm still TBD — see docs/2026-07_re-nkl-struct-findings_reference.md). */
