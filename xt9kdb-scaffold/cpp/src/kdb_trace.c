ET9STATUS XT9KDB(TouchEnd)(ET9KDBInfoPtr ctx, ET9U64 touchId, const float* xs, const float* ys,
                           const ET9U32* ts, ET9U32 count) {
    /* A non-owner's lift neither extends nor recognizes the path; still reported as success. */
    if (foreign_contact(touchId)) {
        g_foreign_drops++;
        XT9KDB_LOGI("TouchEnd: contact %llu is not the session owner %llu — ignored (n=%u)",
                    (unsigned long long)touchId, (unsigned long long)g_session_id, g_n);
        return ET9STATUS_NONE;
    }
    g_session_live = 0;
    push_batch(xs, ys, ts, count);
    ET9STATUS st = process_trace_impl(ctx);
    /* Not propagated: the JNI shim (0x22a58) turns non-zero into touchEnd() == false, which the
     * engine's own dispatcher never returns. */
    XT9KDB_LOGD("TouchEnd n=%u -> recognizer status=%d", g_n, (int)st);
    /* Trail dump for tools/trail_grid_analysis.py: raw point, authored point, resolved key. */
    if (xt9kdb_trace_dump_enabled()) {
        for (ET9U32 i = 0; i < g_n; i++) {
            float ax, ay;
            int kc = xt9kdb_key_code_at(g_buf[i].x, g_buf[i].y, &ax, &ay);
            XT9KDB_LOGI("TRACEPT %u/%u raw=%.1f,%.1f auth=%.1f,%.1f key=%d t=%u",
                        (unsigned)i, (unsigned)g_n,
                        (double)g_buf[i].x, (double)g_buf[i].y,
                        (double)ax, (double)ay, kc, g_buf[i].timestamp);
        }
    }
    return ET9STATUS_NONE;
}

