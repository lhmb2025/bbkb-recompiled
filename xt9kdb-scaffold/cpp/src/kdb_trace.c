ET9STATUS XT9KDB(ProcessStoredTouch)(void* a0, ET9U64 a1, void* a2, ET9U64 a3,
                                     ET9U64 a4, ET9U64 a5, ET9U64 a6, ET9U64 a7) {
    (void)a0;(void)a1;(void)a2;(void)a3;(void)a4;(void)a5;(void)a6;(void)a7;
    return ET9STATUS_NONE;   /* no blob to forward to: offline or DIFF */
}
