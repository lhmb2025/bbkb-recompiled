/* Resolve a sample (RAW sensor coords) to its key code (-1 if none). The stored path stays raw;
 * we map sensor->authored here so point_to_key works against the authored key rects. */
int xt9kdb_key_code_at(float sx, float sy, float* axo, float* ayo) {
    float ax, ay;
    xt9kdb_sensor_to_authored(sx, sy, &ax, &ay);
    if (axo) *axo = ax;
    if (ayo) *ayo = ay;
    int k = xt9kdb_point_to_key(g_kdb_model, ax, ay);
    return (k < 0) ? -1 : (int)g_kdb_model->keys[k].keyCode;
}
/* --- byte-exact result-block record writer (CUTOVER storage) --------------------------------------
 * RE-confirmed layout (TouchStart slot-alloc @0xbbb94 / sample writes @0xbcb64 / finalize):
 *   result = traceObj + 0x49000. TEN slots of 0x7568 at result+0x360 + slot*0x7568; slot 0's early
 *   words double as the header: result+0x370 = round-robin cursor (next slot to try), +0x374 = counter.
 *   Per-slot (relative to record): +0x28 sessionTag 0xBB786DC7, +0x30 startTime, +0x3c seqId,
 *   +0x40 finalize flags 0x00000101, +0x44 STATE (0=free / 2=finalized — also the slot-free probe),
 *   +0x48 sampleCount, +0x50 sample[0] {f32 x, f32 y, u32 t} stride 12. Body memset from +0x18 before init.
 * On-device DIFF (Xt9Trace.dumpTraceRec, XT9REC, 2026-07-04) confirmed +0x00..0x17 all-zero, the +0x28
 * tag, the +0x40 flags, and counter(0x374)==last-seqId. (Earlier docs put 0xAF5B3D8D at +0x28 — that is
 * actually the NKL format magic, a different field.) */
/* Result-block layout, kept for the XT9REC/xt9trace inspectors and the offline tests ONLY.
 * The owned writer that used these is GONE (2026-08-03): nothing polls this block for finished
 * records, so writing it never accomplished anything. Do NOT reintroduce a writer here.
 * In particular result+0x374 must stay ZERO -- ET9KDB_ProcessTrace bails with 0x66 unless it is
 * (0xca588/0xca58c), and nothing ever decrements it, so one stale write disables gestures for good.
 * Two beliefs this file used to assert are also wrong, per the stock-blob A/B: state(+0x44)==2
 * means "finger down" (TouchStart writes it before the first sample), not "finalized"; and
 * result+0x374 is an ACTIVE-TOUCH COUNT, not a pending-record count. */

static void   wr32(char* p, ET9U32 o, ET9U32 v) { memcpy(p + o, &v, 4); }
static ET9U32 rd32(char* p, ET9U32 o)           { ET9U32 v; memcpy(&v, p + o, 4); return v; }
static void   wrf (char* p, ET9U32 o, float  v) { memcpy(p + o, &v, 4); }

