#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
#include <dlfcn.h>
extern ET9STATUS ET9KDB_ProcessTrace(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                     const ET9U32*, ET9U8, ET9U16*) __attribute__((weak));
typedef ET9STATUS (*xt9_blob_trace_fn)(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                       const ET9U32*, ET9U8, ET9U16*);

/* The blob's ET9KDB_ProcessTrace, resolved even when the weak reference below came up NULL.
 *
 * The weak reference binds only if the blob is already loaded when libkb.so is relocated
 * (BIND_NOW). That holds when the blob loads libkb.so as its DT_NEEDED — but Xt9KdbVariant loads
 * libkb.so on its own from DeviceProfile.initialize, and ComposeSettingsActivity calls that. So a
 * process started by keyboard settings loads libkb.so ~2 s before NuanceSDK loads the blob, the
 * weak symbol resolves to NULL, and the loader never revisits it: every swipe for the life of
 * that process failed with "blob symbol did not bind" (KEY2, 2026-09-15; latent since 26ca82a6).
 *
 * Fall back to looking the exported symbol up in the already-loaded blob. RTLD_NOLOAD never loads
 * it, only finds it. A miss is not cached — the blob may simply not be loaded yet — but a hit is. */
static xt9_blob_trace_fn blob_process_trace(void) {
    if (&ET9KDB_ProcessTrace) return ET9KDB_ProcessTrace;
    static xt9_blob_trace_fn resolved;
    if (!resolved) {
        void* blob = dlopen("libnative-lib.so", RTLD_NOW | RTLD_NOLOAD);
        if (blob) {
            resolved = (xt9_blob_trace_fn)dlsym(blob, "ET9KDB_ProcessTrace");
            dlclose(blob);   /* drops only the reference RTLD_NOLOAD added */
            XT9KDB_LOGI("ProcessTrace: weak ref was NULL (libkb loaded before the blob); "
                        "resolved late -> %p", (void*)resolved);
        }
    }
    return resolved;
}
#endif

static ET9STATUS process_trace_impl(ET9KDBInfoPtr ctx) {
    /* L10: no context is "the recognizer could not run", not "nothing to recognize". Counted in
     * every mode, because a NULL handle is a contract violation wherever it happens. */
    if (!ctx) { g_rec_unavailable++; XT9KDB_LOGE("ProcessTrace: ctx NULL"); return ET9STATUS_INVALID_MEMORY; }
    if (g_n == 0) { XT9KDB_LOGE("ProcessTrace: nothing accumulated"); return ET9STATUS_NONE; }

    static ET9KdbTracePt pts[MAX_SAMPLES];
    static ET9U32        times[MAX_SAMPLES];
    ET9U16 out = 0;
    ET9U32 n = g_n;
    for (ET9U32 i = 0; i < g_n; i++) {
        float fx = g_buf[i].x < 0.0f ? 0.0f : g_buf[i].x;   /* 0xca608/0xca610 ucvtf => UNSIGNED */
        float fy = g_buf[i].y < 0.0f ? 0.0f : g_buf[i].y;
        pts[i].x = (ET9U32)fx; pts[i].y = (ET9U32)fy;
        times[i] = g_buf[i].timestamp;
    }
/* __ANDROID__ as well as CUTOVER: the offline cutover selftest compiles with -DXT9KDB_CUTOVER but
 * links no blob, so the symbol would be an unresolvable UNDEF there.
 *
 * WEAK because libkb.so is linked standalone -- the blob is not a link-time input, so a strong
 * reference fails with "undefined symbol: ET9KDB_ProcessTrace". At runtime the blob is already
 * loaded and exports it, so the weak reference binds. If it ever does NOT bind we get a NULL we
 * can log, rather than a load failure or a jump to zero. */
#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
extern ET9STATUS ET9KDB_ProcessTrace(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                     const ET9U32*, ET9U8, ET9U16*) __attribute__((weak));
    /* mode 0xFF mirrors the blob's own kdbRequestHandler (0x1fba4 `mov w1,#0xff`).
     * `out` must be non-NULL: 0xc6678 returns 9 on a NULL out-param.
     * Only in CUTOVER: this resolves to the blob's ET9KDB_ProcessTrace, which is absent from
     * elf_cutover.py's CONTRACT and therefore still defined by the blob. In DIFF/offline builds
     * XT9KDB(name) is xt9kdb_##name and there is no blob to call at all. */
    xt9_blob_trace_fn blob_trace = blob_process_trace();
    if (!blob_trace) {
        g_rec_unavailable++;   /* L10: the one failure that kills swipe for the whole process */
        XT9KDB_LOGE("ProcessTrace: blob symbol did not bind — gesture recognition unavailable");
        return ET9STATUS_NONE;
    }
    xt9kdb_rank_snapshot_store();   /* deposit-time path snapshot for the owned ranker (§8.7.10) */
    ET9STATUS st;
    if (owned_trace_enabled()) {
        st = owned_process_trace(ctx, pts, n, times, 0xFF, &out);
        XT9KDB_LOGI("ProcessTrace(OWNED) n=%u st=%d out=%u", n, (int)st, (unsigned)out);
    } else {
        st = blob_trace(ctx, pts, n, times, 0xFF, &out);
        XT9KDB_LOGI("ProcessTrace(blob) n=%u st=%d out=%u", n, (int)st, (unsigned)out);
    }
    if (st != ET9STATUS_NONE) g_rec_failures++;   /* L10: TouchEnd is about to swallow this */
    return st;
#else
    (void)pts; (void)times; (void)out; (void)n;   /* no blob to call: offline, or a DIFF build */
    return ET9STATUS_NONE;
#endif
}

