/* Expose the current gesture's raw samples to GetKeyPositionByStoredTouch (kdb_geometry.c). */
int xt9kdb_stored_sample(ET9U32 idx, float* x, float* y) {
    if (idx >= g_n) return 0;
    if (x) *x = g_buf[idx].x;
    if (y) *y = g_buf[idx].y;
    return 1;
}

/* ---- rank-path snapshot (§8.7.10) --------------------------------------------------------------
 * The owned ranker must score against the DEPOSITED gesture's path, never the live buffer:
 * g_buf is overwritten by the NEXT swipe's TouchStart/Move on the main thread with no lock
 * involved, so a worker-thread rank that reads it races (complete next path -> off-by-one
 * winners; partial next path -> garbage winners — both observed on corpus-A). This snapshot is
 * written ONCE per gesture at ProcessTrace time (deposit), and the next deposit is serialized
 * behind the Java gesture lock that the bridge holds through ranking — so it is stable exactly
 * for the window the ranker needs. */
static ET9KdbSample g_rank_buf[MAX_SAMPLES];
static ET9U32            g_rank_n;
static ET9U32            g_rank_seq;    /* deposit sequence — consume-once key (§8.7.11) */

void xt9kdb_rank_snapshot_store(void) {
    memcpy(g_rank_buf, g_buf, sizeof(g_buf[0]) * g_n);
    g_rank_n = g_n;
    g_rank_seq++;
    XT9KDB_LOGI("rank snapshot: seq=%u n=%u", g_rank_seq, g_rank_n);
}

ET9U32 xt9kdb_rank_seq(void) { return g_rank_seq; }

int xt9kdb_rank_sample(ET9U32 idx, float* x, float* y) {
    if (idx >= g_rank_n) return 0;
    if (x) *x = g_rank_buf[idx].x;
    if (y) *y = g_rank_buf[idx].y;
    return 1;
}
