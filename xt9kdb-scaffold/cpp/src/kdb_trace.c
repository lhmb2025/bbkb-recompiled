#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
#include <dlfcn.h>
extern ET9STATUS ET9KDB_ProcessTrace(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                     const ET9U32*, ET9U8, ET9U16*) __attribute__((weak));
typedef ET9STATUS (*xt9_blob_trace_fn)(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                       const ET9U32*, ET9U8, ET9U16*);

/* The engine's ET9KDB_ProcessTrace. The weak reference binds only if the engine was loaded when
 * libkb.so was relocated; a process started from keyboard settings loads libkb.so first (via
 * DeviceProfile.initialize), so fall back to dlsym with RTLD_NOLOAD. A miss is not cached. */
static xt9_blob_trace_fn blob_process_trace(void) {
    if (&ET9KDB_ProcessTrace) return ET9KDB_ProcessTrace;
    static xt9_blob_trace_fn resolved;
    if (!resolved) {
        void* blob = dlopen("libnative-lib.so", RTLD_NOW | RTLD_NOLOAD);
        if (blob) {
            resolved = (xt9_blob_trace_fn)dlsym(blob, "ET9KDB_ProcessTrace");
            dlclose(blob);   /* drops only the reference RTLD_NOLOAD added */
            XT9KDB_LOGI("ProcessTrace: weak ref was NULL (libkb loaded before the blob); "
                        "resolved late -> %p", (void*)resolved);
        }
    }
    return resolved;
}
#endif

static ET9STATUS process_trace_impl(ET9KDBInfoPtr ctx) {
    /* No context means the recognizer could not run; counted in every mode. */
    if (!ctx) { g_rec_unavailable++; XT9KDB_LOGE("ProcessTrace: ctx NULL"); return ET9STATUS_INVALID_MEMORY; }
    if (g_n == 0) { XT9KDB_LOGE("ProcessTrace: nothing accumulated"); return ET9STATUS_NONE; }

    static ET9KdbTracePt pts[MAX_SAMPLES];
    static ET9U32        times[MAX_SAMPLES];
    ET9U16 out = 0;
    ET9U32 n = g_n;
    for (ET9U32 i = 0; i < g_n; i++) {
        float fx = g_buf[i].x < 0.0f ? 0.0f : g_buf[i].x;   /* 0xca608/0xca610 ucvtf: unsigned */
        float fy = g_buf[i].y < 0.0f ? 0.0f : g_buf[i].y;
        pts[i].x = (ET9U32)fx; pts[i].y = (ET9U32)fy;
        times[i] = g_buf[i].timestamp;
    }
/* __ANDROID__ too: the offline cutover selftest links no engine. Weak because libkb.so is linked
 * without the engine; an unbound reference is a loggable NULL, not a load failure. */
#if defined(XT9KDB_CUTOVER) && defined(__ANDROID__)
extern ET9STATUS ET9KDB_ProcessTrace(ET9KDBInfoPtr, const ET9KdbTracePt*, ET9U32,
                                     const ET9U32*, ET9U8, ET9U16*) __attribute__((weak));
    /* mode 0xFF as the engine's kdbRequestHandler (0x1fba4 `mov w1,#0xff`); `out` must be
     * non-NULL (0xc6678 returns 9). */
    xt9_blob_trace_fn blob_trace = blob_process_trace();
    if (!blob_trace) {
        g_rec_unavailable++;   /* kills swipe for the whole process */
        XT9KDB_LOGE("ProcessTrace: blob symbol did not bind — gesture recognition unavailable");
        return ET9STATUS_NONE;
    }
    xt9kdb_rank_snapshot_store();   /* deposit-time path snapshot for the owned ranker */
    ET9STATUS st;
    if (owned_trace_enabled()) {
        st = owned_process_trace(ctx, pts, n, times, 0xFF, &out);
        XT9KDB_LOGD("ProcessTrace(OWNED) n=%u st=%d out=%u", n, (int)st, (unsigned)out);
    } else {
        st = blob_trace(ctx, pts, n, times, 0xFF, &out);
        XT9KDB_LOGD("ProcessTrace(blob) n=%u st=%d out=%u", n, (int)st, (unsigned)out);
    }
    if (st != ET9STATUS_NONE) g_rec_failures++;   /* TouchEnd swallows this status */
    return st;
#else
    (void)pts; (void)times; (void)out; (void)n;   /* no engine to call: offline, or a DIFF build */
    return ET9STATUS_NONE;
#endif
}

const void* XT9KDB(_GetLastTrace)(ET9KDBInfoPtr ctx)    { (void)ctx; return g_buf; }
const void* XT9KDB(_GetLastTraceDbg)(ET9KDBInfoPtr ctx) { (void)ctx; return g_buf; }

/* Expose the current gesture's raw samples to GetKeyPositionByStoredTouch (kdb_geometry.c). */
int xt9kdb_stored_sample(ET9U32 idx, float* x, float* y) {
    if (idx >= g_n) return 0;
    if (x) *x = g_buf[idx].x;
    if (y) *y = g_buf[idx].y;
    return 1;
}

/* Rank-path snapshot: the ranker scores the deposited path, never g_buf, which the next swipe
 * overwrites on the main thread without a lock. Written once per gesture at deposit; the next
 * deposit waits on the Java gesture lock the bridge holds through ranking. */
static ET9KdbSample g_rank_buf[MAX_SAMPLES];
static ET9U32            g_rank_n;
static ET9U32            g_rank_seq;    /* deposit sequence, the consume-once key */

void xt9kdb_rank_snapshot_store(void) {
    memcpy(g_rank_buf, g_buf, sizeof(g_buf[0]) * g_n);
    g_rank_n = g_n;
    g_rank_seq++;
    XT9KDB_LOGD("rank snapshot: seq=%u n=%u", g_rank_seq, g_rank_n);
}

ET9U32 xt9kdb_rank_seq(void) { return g_rank_seq; }

int xt9kdb_rank_sample(ET9U32 idx, float* x, float* y) {
    if (idx >= g_rank_n) return 0;
    if (x) *x = g_rank_buf[idx].x;
    if (y) *y = g_rank_buf[idx].y;
    return 1;
}
