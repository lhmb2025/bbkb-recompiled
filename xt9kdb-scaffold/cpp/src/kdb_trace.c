static ET9STATUS owned_process_trace(ET9KDBInfoPtr ctx, const ET9KdbTracePt* pts, ET9U32 count,
                                     const ET9U32* times, ET9U8 mode, ET9U16* out) {
    /* Validator chain mirroring 0xca4cc..0xca558. Same order, same status codes. */
    if (!ctx || !out) return ET9STATUS_INVALID_MEMORY;
    char* c = (char*)ctx;
    ET9U16 magic = *(ET9U16*)(c + 0x58);
    if (magic != 0x1428u)                  return (ET9STATUS)2;
    if (*(ET9U8*)(c + 0x38))               return (ET9STATUS)2;   /* busy */
    if (*(ET9U16*)(c + 0x5a) != magic)     return (ET9STATUS)0x27; /* no KDB loaded */
    char* tr = *(char**)(c + 0x30);
    if (!tr)                               return ET9STATUS_INVALID_MEMORY;
    if (*(ET9U16*)tr != magic)             return (ET9STATUS)2;
    if (!count || !pts || !times)          return ET9STATUS_NONE;

    char* res = tr + 0x49000;
    /* The blob refuses unless this is zero, and nothing ever decrements it. Owning ProcessTrace
     * does not license writing it — ProcessStoredTouch reads the same field. */
    if (rd32(res, 0x374) != 0) {
        XT9KDB_LOGF("owned ProcessTrace: result+0x374=%u (expected 0) - refusing", rd32(res, 0x374));
        return (ET9STATUS)0x66;
    }

    char* rec = res + 0x360;                      /* record[0]; confirmed live 2026-08-12 */
    ET9U32 cap = (0x7568u - REC_SAMPLES_OFF) / 12u;
    if (count > cap) count = cap;

    memset(rec + 0x18, 0, 0x38);                  /* body clear from +0x18, as the blob does */
    *(ET9U8*)(rec + 0x00) = 1;                    /* observed set to 1 immediately before the call */
    wr32(rec, 0x04, 0);
    wr32(rec, 0x08, 1);
    /* Session tag is per-KDB: NKL+0x0c, the loaded layout's content checksum. ProcessTrace reads
     * it as [[ctx+0x60]+0xc]. Hardcoding it is wrong the moment the layout changes. */
    {
        char* nkl = *(char**)(c + ET9_OFF_NKL);
        wr32(rec, 0x28, nkl ? rd32(nkl, 0x0c) : ET9_SESSION_TAG);
    }
    wr32(rec, 0x30, times[0]);                    /* start time  */
    wr32(rec, 0x3c, 0);                           /* sequence id */
    wr32(rec, 0x40, 0x00000101u);                 /* finalize flags */
    wr32(rec, 0x44, 3);                           /* mode: 3 = gesture (0 = tap) */
    wr32(rec, 0x48, count);                       /* sampleCount */
    for (ET9U32 i = 0; i < count; i++) {
        ET9U32 o = REC_SAMPLES_OFF + i * 12u;
        wrf (rec, o + 0, (float)pts[i].x);
        wrf (rec, o + 4, (float)pts[i].y);
        wr32(rec, o + 8, times[i]);
    }

    *out = 0;
    /* Own the decode + AW feed instead of handing the record to the blob's ProcessStoredTouch. The
     * record[0] above is still built (it is cheap and keeps the blob's view consistent).
     * debug.et9.owndecode=1 -> the v2 path (kdb_decode.c + ambiguous sets, §8.7.3); anything else
     * hands the record back to the blob. The superseded first-cut path (debug.et9.ownpst ->
     * decode_keyseq + explicit symbols) no longer ships: see kdb_decode_legacy.c. */
    if (owndecode_mode() == 1) {
        return owned_pst_v2(ctx);
    }
    return XT9KDB(ProcessStoredTouch)(ctx, (ET9U64)mode, out, 1, 0, 0, 0, 0);
}
