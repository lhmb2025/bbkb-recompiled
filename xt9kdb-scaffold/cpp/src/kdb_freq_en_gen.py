#!/usr/bin/env python3
"""kdb_freq_en_gen.py: generate kdb_freq_en.h, the owned decoder's English frequency table.

The table is the BlackBerry LDB's own lexicon: 59,878 words enumerated on the device from the
English LDB trie (the walk lived behind debug.et9.ldbdump in kdb_trace.c and was removed after it
ran; the original generator, tools/w5_ldbtable.py, is in the attic). Each word carries its LDB
frequency RANK (selection-list entry +0x11c, 1 = most common) and that rank mapped to the ranker's
zipf*10 scale:

    zipf10 = round(A + B*log10(rank))     A=77.0  B=-9.8   clamped to [1,255]

LAYOUT (C-6, 2026-11 performance audit). The words used to be `static const char* const
kFreqWordsEn[]`: 59,878 pointers, so libkb.so carried 59,929 relative relocations, a 1.44 MB
.rela.dyn and a 479 KB .data.rel.ro that the dynamic linker writes at load (private dirty memory
in every process that loads the library). They are now ONE string blob, every word NUL-terminated
in table order, plus a uint32_t offset per word: plain .rodata, no relocations. Read word i with
kFreqWordEn(i). Order, zipf and rank are unchanged, and kFreqTableHashEn (FNV-1a over every word,
its zipf and its rank, in order) lets a test prove the C side reads back exactly what was written.

Inputs (one of):
  --from-dump DUMP     word<TAB>rank lines, as the on-device walk wrote them
  --from-header H      an existing kdb_freq_en.h, in either layout (regenerates it losslessly)
Outputs:
  --out H              the header to write (default: kdb_freq_en.h next to this script)
  --tsv T              also write word<TAB>zipf10<TAB>rank, one per line, in table order

  python3 kdb_freq_en_gen.py --from-header kdb_freq_en.h --out kdb_freq_en.h
"""
import argparse, math, os, re, sys

A, B = 77.0, -9.8      # LDB rank -> historical zipf*10 scale (calibration, not corpus data)
ZMIN, ZMAX = 1, 255    # u8; 0 is reserved by the consumer for "absent / treat as nonword"
WORD_RE = re.compile(r"[a-z']+")


def zipf10(rank):
    return max(ZMIN, min(ZMAX, round(A + B * math.log10(max(rank, 1)))))


def from_dump(path):
    best = {}
    for line in open(path):
        if "\t" not in line:
            continue
        w, r = line.rstrip("\n").split("\t")[:2]
        try:
            r = int(r)
        except ValueError:
            continue
        if r <= 0 or not WORD_RE.fullmatch(w):   # echoes/stems carry rank 0
            continue
        if w not in best or r < best[w]:
            best[w] = r
    words = sorted(best)   # byte order == strcmp order (all ASCII): the readers binary-search it
    return [(w, zipf10(best[w]), min(best[w], 65535)) for w in words]


def _array(text, name):
    m = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"no {name}[] in the header")
    return [int(v) for v in re.findall(r"\d+", m.group(1))]


def from_header(path):
    text = open(path).read()
    m = re.search(r"kFreqWordsEn\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if m:   # the old layout: an array of string literals
        words = [s.replace("\\'", "'") for s in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))]
    else:
        m = re.search(r"kFreqWordsBlobEn\[\]\s*=\s*(.*?);", text, re.S)
        if not m:
            sys.exit("neither kFreqWordsEn[] nor kFreqWordsBlobEn[] in the header")
        blob = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
        words = blob.split("\\0")
        if words[-1] != "":
            sys.exit("blob does not end with a NUL")
        words = words[:-1]
    zipf = _array(text, "kFreqZipfEn")
    rank = _array(text, "kFreqRankEn")
    if not (len(words) == len(zipf) == len(rank)):
        sys.exit(f"length mismatch: {len(words)} words, {len(zipf)} zipf, {len(rank)} rank")
    return list(zip(words, zipf, rank))


def table_hash(rows):
    """FNV-1a 32 over each word's bytes, a NUL, its zipf byte and its rank (two bytes, LE)."""
    h = 0x811C9DC5
    for w, z, r in rows:
        for b in w.encode("ascii") + b"\0" + bytes([z, r & 0xFF, r >> 8]):
            h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def check(rows):
    words = [w for w, _, _ in rows]
    for w, z, r in rows:
        if not WORD_RE.fullmatch(w):
            sys.exit(f"bad word {w!r}")
        if not (0 <= z <= 255 and 0 <= r <= 65535):
            sys.exit(f"value out of range for {w!r}: zipf={z} rank={r}")
    for a, b in zip(words, words[1:]):
        if not a.encode() < b.encode():
            sys.exit(f"not strictly sorted: {a!r} then {b!r}")
    if len(words) > 65536:
        sys.exit("more than 65,536 words: the recall index stores word indices as u16")


def emit(rows, out):
    n = len(rows)
    offs, pos = [], 0
    for w, _, _ in rows:
        offs.append(pos)
        pos += len(w) + 1
    L = []
    L.append("/* GENERATED by kdb_freq_en_gen.py from an on-device LDB enumeration — DO NOT EDIT.")
    L.append(f" * {n} English words, sorted; each word's own LDB frequency RANK (+0x11c)")
    L.append(" * mapped to zipf*10 (u8). Lexicon + ordering are the BlackBerry LDB's own (no external corpus).")
    L.append(" * Absent => 0 (treat as rare/nonword; NONWORD threshold = 28 = zipf 2.8).")
    L.append(" * The words are one NUL-separated blob plus offsets, not pointers: no relocations (C-6). */")
    L.append("#include <stdint.h>")
    L.append("")
    L.append(f"/* {pos} bytes: every word NUL-terminated, in table order. */")
    L.append("static const char kFreqWordsBlobEn[] =")
    for i in range(0, n, 8):
        # One literal per word: "a\\0" "1st" can never read as an octal escape.
        L.append("    " + " ".join(f'"{w}\\0"' for w, _, _ in rows[i:i + 8]))
    L.append("    ;")
    L.append("static const uint32_t kFreqWordOffEn[] = {")
    for i in range(0, n, 12):
        L.append("    " + ", ".join(str(o) for o in offs[i:i + 12]) + ",")
    L.append("};")
    L.append("static const unsigned char kFreqZipfEn[] = {")
    for i in range(0, n, 24):
        L.append("    " + ", ".join(str(z) for _, z, _ in rows[i:i + 24]) + ",")
    L.append("};")
    # Raw LDB rank per word (u16, capped at 65535). The ranker uses it ONLY to break exact score
    # ties toward the more-common (lower-rank) word: pool(1894) over poll(1895).
    L.append("static const unsigned short kFreqRankEn[] = {")
    for i in range(0, n, 24):
        L.append("    " + ", ".join(str(r) for _, _, r in rows[i:i + 24]) + ",")
    L.append("};")
    L.append(f"enum {{ kFreqCountEn = {n} }};")
    L.append(f"#define kFreqTableHashEn 0x{table_hash(rows):08x}u   /* see kdb_freq_en_gen.py table_hash */")
    L.append("")
    L.append("/* Word i of the table, 0 <= i < kFreqCountEn. */")
    L.append("static inline const char* kFreqWordEn(int i) { return kFreqWordsBlobEn + kFreqWordOffEn[i]; }")
    open(out, "w").write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--from-dump")
    src.add_argument("--from-header")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "kdb_freq_en.h"))
    ap.add_argument("--tsv")
    a = ap.parse_args()
    rows = from_dump(a.from_dump) if a.from_dump else from_header(a.from_header)
    check(rows)
    if a.tsv:
        with open(a.tsv, "w") as f:
            for w, z, r in rows:
                f.write(f"{w}\t{z}\t{r}\n")
    emit(rows, a.out)
    print(f"wrote {a.out}: {len(rows)} words, hash 0x{table_hash(rows):08x}")


if __name__ == "__main__":
    main()
